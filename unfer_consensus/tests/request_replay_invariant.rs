// D21 (first claim): "a repeated matching request preserves its result", as a
// machine-checked finite model rather than a prose argument about it — over
// *several client incarnations* and a *bounded admission book*.
//
// THE CLAIM. A client names one logical action with a durable `RequestId` and
// retries under that name after a timeout or a restart. Written as the things
// this file checks, over the admission book that answers the retry:
//
//   (R1) A repeated request that carries the same id and the same payload is
//        answered with the result recorded the first time — never `Fresh`, so
//        it cannot be applied twice.
//   (R2) The same id with a different payload is refused as a conflict, and
//        neither the recorded digest nor its outcome changes.
//   (R3) Once a request is at or below the retained floor it is refused, not
//        revived: forgetting a record may not turn a retry into a first
//        delivery.
//   (R4) An outcome, once settled, is not rewritten by a later step.
//   (R5) Incarnations are separate namespaces: a sequence recorded under one
//        incarnation is never answered as a retry of a request under another,
//        and a transition on one client scope changes no other scope.
//   (R6) The bounds hold over the whole search: retained entries never exceed
//        the book's capacity, and live windows never exceed the scope budget or
//        the per-principal incarnation limit. A full book refuses (`AtCapacity`
//        / `IncarnationsExhausted`) instead of evicting a record a client may
//        still retry.
//
// WHAT KIND OF CHECK THIS IS, AND WHAT IT IS NOT. The state is an abstraction of
// `AdmissionBook`: two client scopes (two incarnations of one principal) in the
// exhaustive search, two sequence numbers per scope, two payload digests, three
// admission outcomes, a finite retention floor, and a small capacity. Every
// reachable state is generated by breadth-first search from the empty book, and
// every transition out of every reachable state is checked, so this covers all
// runs of the abstraction — not samples. The conformance driver widens the same
// abstraction to two principals and exercises the scope budget, the per-principal
// incarnation limit and a full book against the real `AdmissionBook`.
//
// What this does **not** do is prove the claim for an unbounded state space by
// induction in a proof assistant; D21's symbolic MM0/Lean induction remains open
// and is named as such in the execution record. The abstraction drops
// persistence, which the D06 tests in `idempotency.rs` cover directly.
//
// RETIREMENT IS THE ONE FORGETTING TRANSITION WITHOUT A FLOOR. `retire` removes
// a window entirely, so a retry under a retired incarnation would be admitted as
// `Fresh`; that is why the client contract says a retired incarnation is never
// retried under. The transition is modelled so conformance covers it, and R3 is
// deliberately *not* claimed to hold across it.
//
// GUARD MUTATIONS. A checker that cannot fail proves nothing. Six mutations of
// the model's rules must each produce a counterexample: answering a repeat as
// `Fresh`, admitting a request whose floor already forgot it, re-settling an
// already-settled outcome, treating another incarnation's record as this one's
// retry, admitting past the capacity bound, and ignoring the per-principal
// incarnation limit.

use std::collections::{HashMap, HashSet, VecDeque};

use unfer_consensus::idempotency::{AdmissionBook, AdmissionVerdict, AdmittedOutcome, RequestId};
use unfer_protocol::Code;
use unfer_protocol::submission::{Refusal, Slot, SubmissionId};

/// Sequence numbers in the abstraction: 1 and 2, so a floor can forget one
/// request and leave the other retained.
const SEQS: usize = 2;
/// The two payload digests the model distinguishes. The real book compares 32
/// bytes; the claim is about equality, not about the digest function.
const DIGESTS: u8 = 2;
/// The highest floor the model can reach.
const TOP_FLOOR: u64 = SEQS as u64;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Outcome {
    Pending,
    Accepted(u64),
    Rejected,
}

impl Outcome {
    fn settled(self) -> bool {
        !matches!(self, Outcome::Pending)
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Entry {
    digest: u8,
    outcome: Outcome,
}

/// The model's answer to an admission attempt. The real `AtCapacity` and
/// `IncarnationsExhausted` carry the bound for diagnostics; the model only needs
/// the kind, because R6 checks the bound over the state itself.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Verdict {
    Fresh,
    Duplicate(Outcome),
    Conflict,
    BelowRetention,
    AtCapacity,
    IncarnationsExhausted,
}

/// One `(deployment, principal, incarnation)` retention window.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Window {
    entry: [Option<Entry>; SEQS],
    floor: u64,
}

impl Window {
    fn fresh() -> Self {
        Window {
            entry: [None; SEQS],
            floor: 0,
        }
    }
}

/// A client scope the model knows how to address. `principal` is only used for
/// the per-principal incarnation bound; the window key is the index.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct Client {
    principal: u8,
    incarnation: u64,
}

#[derive(Clone, Copy, Debug)]
struct Config {
    clients: &'static [Client],
    capacity: usize,
    max_scopes: usize,
    max_incarnations: usize,
}

#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct State {
    /// One slot per configured client; `None` means the window does not exist
    /// (never admitted, or retired).
    clients: Vec<Option<Window>>,
}

impl State {
    fn fresh(config: &Config) -> Self {
        State {
            clients: vec![None; config.clients.len()],
        }
    }

    fn sequence(index: usize) -> u64 {
        index as u64 + 1
    }

    fn entries(&self) -> usize {
        self.clients
            .iter()
            .flatten()
            .map(|window| window.entry.iter().flatten().count())
            .sum()
    }

    fn windows(&self) -> usize {
        self.clients.iter().flatten().count()
    }

    fn incarnations_of(&self, config: &Config, principal: u8) -> usize {
        self.clients
            .iter()
            .enumerate()
            .filter(|(index, window)| {
                window.is_some() && config.clients[*index].principal == principal
            })
            .count()
    }
}

/// How a rule is bent by a guard mutation. `None` is the model as the code
/// describes it; each variant deliberately breaks one rule so the checker has to
/// notice.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mutation {
    None,
    /// `admit` answers a repeat as `Fresh`, so the caller would submit it again.
    DuplicateFresh,
    /// `admit` revives a sequence the retained floor already forgot.
    PruneRevives,
    /// `settle` overwrites an outcome that was already settled.
    SettleAny,
    /// `admit` answers a request in one incarnation with another incarnation's
    /// recorded result.
    CrossIncarnation,
    /// `admit` ignores the book's capacity bound and records past it.
    EvictAtCapacity,
    /// `admit` ignores the per-principal incarnation limit.
    IgnoreIncarnationLimit,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Op {
    Admit {
        client: usize,
        seq: usize,
        digest: u8,
    },
    Record {
        client: usize,
        seq: usize,
        digest: u8,
    },
    Settle {
        client: usize,
        seq: usize,
        outcome: Outcome,
    },
    Acknowledge {
        client: usize,
        through: u64,
    },
    Retire {
        client: usize,
    },
}

impl Op {
    fn label(self, config: &Config) -> String {
        let scope = |client: usize| {
            let client = config.clients[client];
            format!("p{}#{}", client.principal, client.incarnation)
        };
        match self {
            Op::Admit {
                client,
                seq,
                digest,
            } => format!("admit {} seq {} digest {digest}", scope(client), seq + 1),
            Op::Record {
                client,
                seq,
                digest,
            } => format!("record {} seq {} digest {digest}", scope(client), seq + 1),
            Op::Settle {
                client,
                seq,
                outcome,
            } => format!("settle {} seq {} -> {outcome:?}", scope(client), seq + 1),
            Op::Acknowledge { client, through } => {
                format!("acknowledge {} through {through}", scope(client))
            }
            Op::Retire { client } => format!("retire {}", scope(client)),
        }
    }
}

/// The admission rule, written from the D06 contract rather than from the
/// implementation: a request at or below the floor is refused; a retained id with
/// the same digest replays its result; a retained id with another digest is a
/// conflict; anything else is fresh unless the book or the incarnation budget is
/// full — and a full book refuses rather than evicting.
fn admit(
    state: &State,
    config: &Config,
    client: usize,
    seq: usize,
    digest: u8,
    mutation: Mutation,
) -> Verdict {
    if let Some(window) = &state.clients[client] {
        if mutation != Mutation::PruneRevives && State::sequence(seq) <= window.floor {
            return Verdict::BelowRetention;
        }
        if let Some(entry) = window.entry[seq] {
            return if mutation == Mutation::DuplicateFresh {
                Verdict::Fresh
            } else if entry.digest == digest {
                Verdict::Duplicate(entry.outcome)
            } else {
                Verdict::Conflict
            };
        }
    }
    if mutation == Mutation::CrossIncarnation {
        // The bug this models: lookup by sequence across every window, so a
        // fresh incarnation appears to replay a previous run's request.
        for (index, other) in state.clients.iter().enumerate() {
            if index == client {
                continue;
            }
            if let Some(entry) = other.as_ref().and_then(|window| window.entry[seq]) {
                return if entry.digest == digest {
                    Verdict::Duplicate(entry.outcome)
                } else {
                    Verdict::Conflict
                };
            }
        }
    }
    if mutation != Mutation::EvictAtCapacity && state.entries() >= config.capacity {
        return Verdict::AtCapacity;
    }
    let principal = config.clients[client].principal;
    let known = state.incarnations_of(config, principal);
    if state.clients[client].is_none()
        && mutation != Mutation::IgnoreIncarnationLimit
        && known >= config.max_incarnations
    {
        return Verdict::IncarnationsExhausted;
    }
    if state.clients[client].is_none() && state.windows() >= config.max_scopes {
        return Verdict::AtCapacity;
    }
    Verdict::Fresh
}

fn apply(
    state: &State,
    config: &Config,
    op: Op,
    mutation: Mutation,
) -> Result<State, &'static str> {
    let mut next = state.clone();
    match op {
        // `admit` is a probe: the real method takes `&self` and records
        // nothing, which is what makes an ingress failure retryable.
        Op::Admit { .. } => {}
        Op::Record {
            client,
            seq,
            digest,
        } => {
            if admit(state, config, client, seq, digest, mutation) != Verdict::Fresh {
                return Err("NOT_FRESH");
            }
            let window = next.clients[client].get_or_insert_with(Window::fresh);
            window.entry[seq] = Some(Entry {
                digest,
                outcome: Outcome::Pending,
            });
        }
        Op::Settle {
            client,
            seq,
            outcome,
        } => {
            let entry = next.clients[client]
                .as_ref()
                .and_then(|window| window.entry[seq])
                .ok_or("NOT_RECORDED")?;
            if entry.outcome.settled() && mutation != Mutation::SettleAny {
                return Err("ALREADY_SETTLED");
            }
            let window = next.clients[client]
                .as_mut()
                .expect("a recorded entry has a window");
            window.entry[seq] = Some(Entry {
                digest: entry.digest,
                outcome,
            });
        }
        Op::Acknowledge { client, through } => {
            let Some(window) = next.clients[client].as_mut() else {
                return Ok(next);
            };
            let floor = through.max(window.floor).min(TOP_FLOOR);
            window.floor = floor;
            for index in 0..SEQS {
                if State::sequence(index) <= floor {
                    window.entry[index] = None;
                }
            }
        }
        Op::Retire { client } => {
            next.clients[client] = None;
        }
    }
    Ok(next)
}

/// Which of the claims a reachable state violates, if any.
fn violations(state: &State, config: &Config) -> Vec<&'static str> {
    let mut out = Vec::new();
    // R6: the bounds are invariants of the book, not just of the probe.
    if state.entries() > config.capacity {
        out.push("R6 the retained entry count exceeds the capacity");
    }
    if state.windows() > config.max_scopes {
        out.push("R6 the live window count exceeds the scope budget");
    }
    let mut principals: HashMap<u8, usize> = HashMap::new();
    for (index, window) in state.clients.iter().enumerate() {
        if window.is_some() {
            *principals
                .entry(config.clients[index].principal)
                .or_default() += 1;
        }
    }
    for count in principals.values() {
        if *count > config.max_incarnations {
            out.push("R6 a principal holds more incarnations than the limit");
        }
    }
    for (index, window) in state.clients.iter().enumerate() {
        let Some(window) = window else {
            continue;
        };
        for seq in 0..SEQS {
            match window.entry[seq] {
                Some(entry) => {
                    if State::sequence(seq) <= window.floor {
                        out.push("R3 a request at or below the retained floor is still retained");
                    }
                    match admit(state, config, index, seq, entry.digest, Mutation::None) {
                        Verdict::Duplicate(outcome) if outcome == entry.outcome => {}
                        _ => out.push("R1 a repeated matching request does not return its result"),
                    }
                    let other = (entry.digest + 1) % DIGESTS;
                    match admit(state, config, index, seq, other, Mutation::None) {
                        Verdict::Conflict => {}
                        Verdict::BelowRetention if State::sequence(seq) <= window.floor => {}
                        _ => out.push("R2 a different payload for an admitted id is not refused"),
                    }
                }
                None => {
                    if State::sequence(seq) <= window.floor
                        && admit(state, config, index, seq, 0, Mutation::None)
                            != Verdict::BelowRetention
                    {
                        out.push("R3 a forgotten request is admitted again");
                    }
                }
            }
        }
    }
    out
}

/// Every operation the model exposes, with every argument.
fn all_ops(config: &Config) -> Vec<Op> {
    let mut ops = Vec::new();
    for client in 0..config.clients.len() {
        for seq in 0..SEQS {
            for digest in 0..DIGESTS {
                ops.push(Op::Admit {
                    client,
                    seq,
                    digest,
                });
                ops.push(Op::Record {
                    client,
                    seq,
                    digest,
                });
            }
            for outcome in [Outcome::Pending, Outcome::Accepted(1), Outcome::Rejected] {
                ops.push(Op::Settle {
                    client,
                    seq,
                    outcome,
                });
            }
        }
        for through in 0..=TOP_FLOOR {
            ops.push(Op::Acknowledge { client, through });
        }
        ops.push(Op::Retire { client });
    }
    ops
}

struct Exploration {
    states: usize,
    transitions: usize,
    duplicates: usize,
    conflicts: usize,
    settled: usize,
    below_retention: usize,
    at_capacity: usize,
    exhausted: usize,
    first_violation: Option<(State, Op, String)>,
    traces: HashMap<State, (State, String)>,
}

fn explore(config: &Config, mutation: Mutation) -> Exploration {
    let mut seen: HashSet<State> = HashSet::new();
    let mut queue: VecDeque<State> = VecDeque::new();
    let mut traces: HashMap<State, (State, String)> = HashMap::new();
    let mut transitions = 0usize;
    let mut duplicates = 0usize;
    let mut conflicts = 0usize;
    let mut settled = 0usize;
    let mut below_retention = 0usize;
    let mut at_capacity = 0usize;
    let mut exhausted = 0usize;
    let mut first_violation: Option<(State, Op, String)> = None;
    let ops = all_ops(config);

    let init = State::fresh(config);
    seen.insert(init.clone());
    queue.push_back(init);
    while let Some(state) = queue.pop_front() {
        for op in &ops {
            transitions += 1;
            if let Op::Admit {
                client,
                seq,
                digest,
            } = *op
            {
                match admit(&state, config, client, seq, digest, mutation) {
                    Verdict::Duplicate(_) => duplicates += 1,
                    Verdict::Conflict => conflicts += 1,
                    Verdict::BelowRetention => below_retention += 1,
                    Verdict::AtCapacity => at_capacity += 1,
                    Verdict::IncarnationsExhausted => exhausted += 1,
                    Verdict::Fresh => {}
                }
                // R5 (probe half): another incarnation's recorded result must
                // never answer this one's request.
                if mutation == Mutation::CrossIncarnation {
                    let isolated = admit(&state, config, client, seq, digest, Mutation::None);
                    let observed = admit(&state, config, client, seq, digest, mutation);
                    if !same_outcome_kind(isolated, observed) {
                        first_violation.get_or_insert((
                            state.clone(),
                            *op,
                            "R5 a request in another incarnation was treated as this retry"
                                .to_string(),
                        ));
                    }
                }
            }
            match apply(&state, config, *op, mutation) {
                Ok(next) => {
                    // R1 (transition half): a request that is already recorded
                    // must not be admitted as fresh. This is the rule the
                    // `DuplicateFresh` mutation breaks.
                    if let Op::Record {
                        client,
                        seq,
                        digest,
                    } = *op
                        && state.clients[client]
                            .as_ref()
                            .is_some_and(|window| window.entry[seq].is_some())
                        && admit(&state, config, client, seq, digest, mutation) == Verdict::Fresh
                    {
                        first_violation.get_or_insert((
                            state.clone(),
                            *op,
                            "R1 a repeated matching request was admitted as fresh".to_string(),
                        ));
                    }
                    if let Op::Settle { client, seq, .. } = *op
                        && state.clients[client]
                            .as_ref()
                            .is_some_and(|window| window.entry[seq].is_some())
                    {
                        settled += 1;
                    }
                    for index in 0..config.clients.len() {
                        let before = state.clients[index];
                        let after = next.clients[index];
                        // R5 (transition half): a step on one client scope must
                        // not change another.
                        if index != op_client(*op) && before != after {
                            first_violation.get_or_insert((
                                state.clone(),
                                *op,
                                "R5 a step changed a different client scope".to_string(),
                            ));
                        }
                        let (Some(before), Some(after)) = (before, after) else {
                            // Retirement removes a window wholesale; that is the
                            // one documented forgetting transition without a
                            // floor, so R3 is not claimed across it.
                            continue;
                        };
                        for seq in 0..SEQS {
                            let (Some(entry_before), Some(entry_after)) =
                                (before.entry[seq], after.entry[seq])
                            else {
                                if before.entry[seq].is_some()
                                    && after.entry[seq].is_none()
                                    && State::sequence(seq) > after.floor
                                {
                                    first_violation.get_or_insert((
                                        state.clone(),
                                        *op,
                                        "R1 an outcome was dropped without a raised floor"
                                            .to_string(),
                                    ));
                                }
                                continue;
                            };
                            if entry_before.digest != entry_after.digest {
                                first_violation.get_or_insert((
                                    state.clone(),
                                    *op,
                                    "R2 a recorded payload digest was overwritten".to_string(),
                                ));
                            }
                            if entry_before.outcome.settled()
                                && entry_before.outcome != entry_after.outcome
                            {
                                first_violation.get_or_insert((
                                    state.clone(),
                                    *op,
                                    "R4 a settled outcome was rewritten".to_string(),
                                ));
                            }
                        }
                    }
                    for violation in violations(&next, config) {
                        first_violation.get_or_insert((state.clone(), *op, violation.to_string()));
                    }
                    if seen.insert(next.clone()) {
                        traces.insert(
                            next.clone(),
                            (state.clone(), format!("{} → {next:?}", op.label(config))),
                        );
                        queue.push_back(next);
                    }
                }
                Err(_) => {
                    // A refused step must not change the state: the model returns
                    // the input unchanged by construction, like the real book's
                    // `&self` probe or a caller that only records after `Fresh`.
                }
            }
        }
    }
    Exploration {
        states: seen.len(),
        transitions,
        duplicates,
        conflicts,
        settled,
        below_retention,
        at_capacity,
        exhausted,
        first_violation,
        traces,
    }
}

fn op_client(op: Op) -> usize {
    match op {
        Op::Admit { client, .. }
        | Op::Record { client, .. }
        | Op::Settle { client, .. }
        | Op::Acknowledge { client, .. }
        | Op::Retire { client } => client,
    }
}

/// Whether two verdicts are the same answer, ignoring a bound's numeric value.
fn same_outcome_kind(left: Verdict, right: Verdict) -> bool {
    match (left, right) {
        (Verdict::Fresh, Verdict::Fresh)
        | (Verdict::Conflict, Verdict::Conflict)
        | (Verdict::BelowRetention, Verdict::BelowRetention)
        | (Verdict::AtCapacity, Verdict::AtCapacity)
        | (Verdict::IncarnationsExhausted, Verdict::IncarnationsExhausted) => true,
        (Verdict::Duplicate(left), Verdict::Duplicate(right)) => left == right,
        _ => false,
    }
}

fn witness(mut state: State, traces: &HashMap<State, (State, String)>) -> Vec<String> {
    let mut path = Vec::new();
    let mut guard = 0;
    while let Some((parent, label)) = traces.get(&state) {
        path.push(label.clone());
        state = parent.clone();
        guard += 1;
        if guard > 64 {
            break;
        }
    }
    path.reverse();
    path
}

/// The exhaustive configuration: three incarnations of one principal, a book
/// that retains two requests, and both the scope budget and the incarnation limit
/// set so each can be reached. Three incarnations are needed because the real
/// book checks the capacity bound before the incarnation bound: only after an
/// acknowledgement frees entries can a third window be attempted, and only then
/// does the per-principal limit answer.
fn exploration_config() -> Config {
    static CLIENTS: [Client; 3] = [
        Client {
            principal: 0,
            incarnation: 1,
        },
        Client {
            principal: 0,
            incarnation: 2,
        },
        Client {
            principal: 0,
            incarnation: 3,
        },
    ];
    Config {
        clients: &CLIENTS,
        capacity: 2,
        max_scopes: 3,
        max_incarnations: 2,
    }
}

#[test]
fn the_request_replay_invariant_holds_over_every_reachable_state() {
    let config = exploration_config();
    let e = explore(&config, Mutation::None);
    if let Some((state, op, violation)) = &e.first_violation {
        let path = witness(state.clone(), &e.traces);
        panic!(
            "request replay invariant violated: {violation}\nafter: {path:?}\nthen: {}",
            op.label(&config)
        );
    }
    // Coverage, not just "no failure": a search that never replayed a request,
    // never saw a conflict, never hit a bound, or never settled one would pass
    // vacuously.
    assert!(e.states > 10, "only {} states reached", e.states);
    assert!(
        e.duplicates > 0,
        "no repeated matching request was ever answered"
    );
    assert!(e.conflicts > 0, "no conflicting payload was ever offered");
    assert!(e.settled > 0, "no outcome was ever settled");
    assert!(
        e.below_retention > 0,
        "the retention floor was never exercised"
    );
    assert!(e.at_capacity > 0, "the capacity bound was never exercised");
    assert!(e.exhausted > 0, "the incarnation limit was never exercised");
    println!(
        "request replay: states={} transitions={} duplicates={} conflicts={} settled={} below_retention={} at_capacity={} exhausted={} violations=0",
        e.states,
        e.transitions,
        e.duplicates,
        e.conflicts,
        e.settled,
        e.below_retention,
        e.at_capacity,
        e.exhausted
    );
}

#[test]
fn each_replay_mutation_is_caught_with_a_witness() {
    let config = exploration_config();
    let cases = [
        (Mutation::DuplicateFresh, "R1"),
        (Mutation::PruneRevives, "R3"),
        (Mutation::SettleAny, "R4"),
        (Mutation::CrossIncarnation, "R5"),
        (Mutation::EvictAtCapacity, "R6"),
        (Mutation::IgnoreIncarnationLimit, "R6"),
    ];
    for (mutation, expected) in cases {
        let e = explore(&config, mutation);
        let (state, op, violation) = e
            .first_violation
            .unwrap_or_else(|| panic!("mutation {mutation:?} was not caught"));
        assert!(
            violation.starts_with(expected),
            "mutation {mutation:?}: expected {expected}, got {violation}"
        );
        let path = witness(state, &e.traces);
        println!(
            "mutation {mutation:?}: caught ({violation}) after {} step(s), last: {}",
            path.len(),
            op.label(&config)
        );
    }
}

// ---------------------------------------------------------------------------
// Conformance: the model is a *specification*, so it must describe the real
// `AdmissionBook` and not a tidier cousin of it. Both are driven with the same
// deterministic pseudo-random sequence of legal steps across two principals and
// their incarnations, with the capacity, scope budget and incarnation limit
// small enough that every bound is reached. After every step the verdict and the
// whole observable state (per-window digest, outcome and floor) are compared.
// ---------------------------------------------------------------------------

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

fn conformance_config() -> Config {
    static CLIENTS: [Client; 4] = [
        Client {
            principal: 0,
            incarnation: 1,
        },
        Client {
            principal: 0,
            incarnation: 2,
        },
        Client {
            principal: 0,
            incarnation: 3,
        },
        Client {
            principal: 1,
            incarnation: 1,
        },
    ];
    Config {
        clients: &CLIENTS,
        capacity: 3,
        max_scopes: 3,
        max_incarnations: 2,
    }
}

fn digests() -> [[u8; 32]; DIGESTS as usize] {
    [[0u8; 32], [1u8; 32]]
}

fn id(config: &Config, client: usize, seq: usize) -> RequestId {
    let client = config.clients[client];
    RequestId::new(
        "d21",
        format!("principal-{}", client.principal),
        client.incarnation,
        seq as u64 + 1,
    )
}

fn digest_index(bytes: &[u8; 32]) -> u8 {
    bytes[0]
}

fn model_outcome(outcome: &AdmittedOutcome) -> Outcome {
    match outcome {
        AdmittedOutcome::Pending { .. } => Outcome::Pending,
        AdmittedOutcome::Accepted { slot, .. } => Outcome::Accepted(slot.0),
        AdmittedOutcome::Rejected(_) => Outcome::Rejected,
    }
}

fn model_verdict(verdict: &AdmissionVerdict) -> Verdict {
    match verdict {
        AdmissionVerdict::Fresh => Verdict::Fresh,
        AdmissionVerdict::Duplicate(outcome) => Verdict::Duplicate(model_outcome(outcome)),
        AdmissionVerdict::Conflict { .. } => Verdict::Conflict,
        AdmissionVerdict::BelowRetention { .. } => Verdict::BelowRetention,
        AdmissionVerdict::AtCapacity { .. } => Verdict::AtCapacity,
        AdmissionVerdict::IncarnationsExhausted { .. } => Verdict::IncarnationsExhausted,
    }
}

fn observe(book: &AdmissionBook, config: &Config) -> State {
    let mut state = State::fresh(config);
    for client in 0..config.clients.len() {
        let mut window = Window::fresh();
        let mut seen = false;
        for seq in 0..SEQS {
            let id = id(config, client, seq);
            if let Some(admission) = book.admission(&id) {
                window.entry[seq] = Some(Entry {
                    digest: digest_index(&admission.digest),
                    outcome: model_outcome(&admission.outcome),
                });
            }
            if let Some(floor) = book.floor(&id) {
                window.floor = floor;
                seen = true;
            }
        }
        if seen {
            state.clients[client] = Some(window);
        }
    }
    state
}

fn refused() -> Refusal {
    Refusal::new(Code::BAD_JSON, "domain refusal")
}

#[test]
fn the_model_and_the_real_admission_book_agree_on_every_step() {
    let config = conformance_config();
    let mut rng = Rng(0xD1B5_4A32_D192_ED03);
    let digests = digests();
    let mut compared = 0usize;
    let mut replays = 0usize;
    let mut below_retention = 0usize;
    let mut at_capacity = 0usize;
    let mut exhausted = 0usize;
    let mut retires = 0usize;

    for sequence in 0..200 {
        let mut book = AdmissionBook::new(config.capacity)
            .with_incarnation_limits(config.max_scopes, config.max_incarnations);
        let mut model = State::fresh(&config);

        for turn in 0..16 {
            let client = rng.below(config.clients.len() as u64) as usize;
            let seq = rng.below(SEQS as u64) as usize;
            let digest = rng.below(DIGESTS as u64) as u8;
            // The driver prefers the admission probe, because that is what a
            // retrying client actually calls; the other steps follow it.
            let op = match rng.below(6) {
                0 | 1 => Op::Admit {
                    client,
                    seq,
                    digest,
                },
                2 => Op::Record {
                    client,
                    seq,
                    digest,
                },
                3 => Op::Settle {
                    client,
                    seq,
                    outcome: if rng.below(2) == 0 {
                        Outcome::Accepted(1)
                    } else {
                        Outcome::Rejected
                    },
                },
                4 => Op::Acknowledge {
                    client,
                    through: rng.below(TOP_FLOOR + 1),
                },
                _ => Op::Retire { client },
            };

            let verdict = match op {
                Op::Admit {
                    client,
                    seq,
                    digest,
                } => {
                    let modeled = admit(&model, &config, client, seq, digest, Mutation::None);
                    let real = book.admit(&id(&config, client, seq), digests[digest as usize]);
                    let observed = model_verdict(&real);
                    assert!(
                        same_outcome_kind(modeled, observed),
                        "sequence {sequence} turn {turn}: model says {modeled:?} for {}; the book says {observed:?}",
                        op.label(&config)
                    );
                    match observed {
                        Verdict::Duplicate(_) => replays += 1,
                        Verdict::BelowRetention => below_retention += 1,
                        Verdict::AtCapacity => at_capacity += 1,
                        Verdict::IncarnationsExhausted => exhausted += 1,
                        _ => {}
                    }
                    Some(observed)
                }
                _ => None,
            };

            if verdict.is_some() {
                assert!(
                    apply(&model, &config, op, Mutation::None).is_ok(),
                    "an admission probe never fails"
                );
            } else {
                let legal = match op {
                    Op::Record {
                        client,
                        seq,
                        digest,
                    } => {
                        admit(&model, &config, client, seq, digest, Mutation::None)
                            == Verdict::Fresh
                    }
                    Op::Settle { client, seq, .. } => model.clients[client]
                        .as_ref()
                        .and_then(|window| window.entry[seq])
                        .map(|entry| !entry.outcome.settled())
                        .unwrap_or(false),
                    Op::Acknowledge { .. } | Op::Retire { .. } => true,
                    Op::Admit { .. } => unreachable!(),
                };
                if legal {
                    // The model's step must be accepted whenever the driver
                    // performs the corresponding real step.
                    let next = apply(&model, &config, op, Mutation::None)
                        .unwrap_or_else(|error| panic!("legal step refused by the model: {error}"));
                    match op {
                        Op::Record {
                            client,
                            seq,
                            digest,
                        } => {
                            book.record(
                                &id(&config, client, seq),
                                SubmissionId(7),
                                digests[digest as usize],
                            );
                        }
                        Op::Settle {
                            client,
                            seq,
                            outcome,
                        } => {
                            let outcome = match outcome {
                                Outcome::Accepted(slot) => AdmittedOutcome::Accepted {
                                    submission: SubmissionId(7),
                                    slot: Slot(slot),
                                },
                                Outcome::Rejected => AdmittedOutcome::Rejected(refused()),
                                Outcome::Pending => AdmittedOutcome::Pending {
                                    submission: SubmissionId(7),
                                },
                            };
                            book.settle(&id(&config, client, seq), outcome);
                        }
                        Op::Acknowledge { client, through } => {
                            book.acknowledge(&id(&config, client, seq), through);
                        }
                        Op::Retire { client } => {
                            let client_key = config.clients[client];
                            let retired = book.retire_incarnation(
                                "d21",
                                &format!("principal-{}", client_key.principal),
                                client_key.incarnation,
                            );
                            retires += usize::from(retired);
                        }
                        Op::Admit { .. } => unreachable!(),
                    }
                    model = next;
                }
            }

            // Whole-state equality, not just the verdict: every window's digest,
            // outcome and floor must agree after every step.
            assert_eq!(
                model,
                observe(&book, &config),
                "sequence {sequence} turn {turn}: state diverged after {}",
                op.label(&config)
            );
            assert_eq!(
                model.entries(),
                book.len(),
                "sequence {sequence} turn {turn}: retained counts disagree"
            );
            if let Some(violation) = violations(&model, &config).first() {
                panic!("model invariant violated in conformance run: {violation}");
            }
            compared += 1;
        }
    }
    assert!(replays > 0, "no repeated request was ever replayed");
    assert!(below_retention > 0, "the retention floor was never reached");
    assert!(
        at_capacity > 0,
        "the capacity/scope bound was never reached"
    );
    assert!(
        exhausted > 0,
        "the per-principal incarnation limit was never reached"
    );
    assert!(retires > 0, "no incarnation was ever retired");
    println!(
        "replay conformance: {compared} steps compared, 0 disagreements, {replays} replays answered, {below_retention} below retention, {at_capacity} at capacity, {exhausted} incarnation-limited, {retires} retirements"
    );
}

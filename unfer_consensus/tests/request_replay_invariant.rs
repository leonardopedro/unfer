// D21 (first claim): "a repeated matching request preserves its result", as a
// machine-checked finite model rather than a prose argument about it.
//
// THE CLAIM. A client names one logical action with a durable `RequestId` and
// retries under that name after a timeout or a restart. Written as the things
// this file checks, over the admission book that answers the retry:
//
//   (R1) A repeated request that carries the same id and the same payload is
//        answered with the result recorded the first time — never `Fresh`, so
//        it cannot be applied twice.
//   (R2) The same id with a different payload is refused as a conflict, and
//        neither the recorded digest nor its outcome changes.
//   (R3) Once a request is at or below the retained floor it is refused, not
//        revived: forgetting a record may not turn a retry into a first
//        delivery.
//   (R4) An outcome, once settled, is not rewritten by a later step.
//
// WHAT KIND OF CHECK THIS IS, AND WHAT IT IS NOT. The state is an abstraction of
// `AdmissionBook`: one client scope (one deployment/principal/incarnation) with
// two sequence numbers, two payload digests, four admission outcomes, and a
// finite retention floor. Every reachable state is generated by breadth-first
// search from the empty book, and every transition out of every reachable state
// is checked, so this covers all runs of the abstraction — not samples.
//
// The abstraction keeps the parts the claim depends on (identity, payload
// binding, the floor, and the settle-once rule) and drops the parts it does not
// (capacity accounting, incarnation limits, persistence), which the D06 tests in
// `idempotency.rs` cover directly. What this does **not** do is prove the claim
// for an unbounded state space by induction in a proof assistant; D21's symbolic
// MM0/Lean induction remains open and is named as such in the execution record.
//
// GUARD MUTATIONS. A checker that cannot fail proves nothing. Three mutations of
// the model's rules must each produce a counterexample: answering a repeat as
// `Fresh`, admitting a request whose floor already forgot it, and re-settling an
// already-settled outcome.

use std::collections::{HashMap, HashSet, VecDeque};

use unfer_consensus::idempotency::{AdmissionBook, AdmissionVerdict, AdmittedOutcome, RequestId};
use unfer_protocol::Code;
use unfer_protocol::submission::{Refusal, Slot, SubmissionId};

/// Sequence numbers in the abstraction: 1 and 2, so a floor can forget one
/// request and leave the other retained.
const SEQS: u64 = 2;
/// The two payload digests the model distinguishes. The real book compares 32
/// bytes; the claim is about equality, not about the digest function.
const DIGESTS: u8 = 2;
/// The highest floor the model can reach.
const TOP_FLOOR: u64 = SEQS;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Outcome {
    Pending,
    Accepted(u64),
    Rejected,
}

impl Outcome {
    fn settled(self) -> bool {
        !matches!(self, Outcome::Pending)
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Entry {
    digest: u8,
    outcome: Outcome,
}

/// The model's answer to an admission attempt.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Verdict {
    Fresh,
    Duplicate(Outcome),
    Conflict,
    BelowRetention,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct State {
    entry: [Option<Entry>; SEQS as usize],
    /// Whether this client scope has a retention window at all. `acknowledge` on
    /// an unknown scope is a no-op in the real book, so the model cannot raise a
    /// floor before something was recorded.
    known: bool,
    floor: u64,
}

impl State {
    fn fresh() -> Self {
        State {
            entry: [None; SEQS as usize],
            known: false,
            floor: 0,
        }
    }

    fn sequence(index: usize) -> u64 {
        index as u64 + 1
    }
}

/// How a rule is bent by a guard mutation. `None` is the model as the code
/// describes it; each variant deliberately breaks one rule so the checker has to
/// notice.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mutation {
    None,
    /// `admit` answers a repeat as `Fresh`, so the caller would submit it again.
    DuplicateFresh,
    /// `admit` revives a sequence the retained floor already forgot.
    PruneRevives,
    /// `settle` overwrites an outcome that was already settled.
    SettleAny,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Op {
    Admit { seq: usize, digest: u8 },
    Record { seq: usize, digest: u8 },
    Settle { seq: usize, outcome: Outcome },
    Acknowledge { through: u64 },
}

impl Op {
    fn label(self) -> String {
        match self {
            Op::Admit { seq, digest } => format!("admit seq {} digest {digest}", seq + 1),
            Op::Record { seq, digest } => format!("record seq {} digest {digest}", seq + 1),
            Op::Settle { seq, outcome } => format!("settle seq {} -> {outcome:?}", seq + 1),
            Op::Acknowledge { through } => format!("acknowledge through {through}"),
        }
    }
}

/// The admission rule, written from the D06 contract rather than from the
/// implementation: a request at or below the floor is refused; a retained id with
/// the same digest replays its result; a retained id with another digest is a
/// conflict; anything else is fresh.
fn admit(state: &State, seq: usize, digest: u8, mutation: Mutation) -> Verdict {
    if mutation != Mutation::PruneRevives && State::sequence(seq) <= state.floor {
        return Verdict::BelowRetention;
    }
    match state.entry[seq] {
        Some(_) if mutation == Mutation::DuplicateFresh => Verdict::Fresh,
        Some(entry) if entry.digest == digest => Verdict::Duplicate(entry.outcome),
        Some(_) => Verdict::Conflict,
        None => Verdict::Fresh,
    }
}

fn apply(state: &State, op: Op, mutation: Mutation) -> Result<State, &'static str> {
    let mut next = *state;
    match op {
        // `admit` is a probe: the real method takes `&self` and records nothing,
        // which is what makes an ingress failure retryable.
        Op::Admit { .. } => {}
        Op::Record { seq, digest } => {
            if admit(state, seq, digest, mutation) != Verdict::Fresh {
                return Err("NOT_FRESH");
            }
            next.entry[seq] = Some(Entry {
                digest,
                outcome: Outcome::Pending,
            });
            next.known = true;
        }
        Op::Settle { seq, outcome } => {
            let entry = next.entry[seq].ok_or("NOT_RECORDED")?;
            if entry.outcome.settled() && mutation != Mutation::SettleAny {
                return Err("ALREADY_SETTLED");
            }
            next.entry[seq] = Some(Entry {
                digest: entry.digest,
                outcome,
            });
        }
        Op::Acknowledge { through } => {
            if !state.known {
                return Ok(next);
            }
            let floor = through.max(state.floor).min(TOP_FLOOR);
            next.floor = floor;
            for index in 0..SEQS as usize {
                if State::sequence(index) <= floor {
                    next.entry[index] = None;
                }
            }
        }
    }
    Ok(next)
}

/// Which of the four claims a reachable state violates, if any.
fn violations(state: &State) -> Vec<&'static str> {
    let mut out = Vec::new();
    for index in 0..SEQS as usize {
        match state.entry[index] {
            Some(entry) => {
                if State::sequence(index) <= state.floor {
                    out.push("R3 a request at or below the retained floor is still retained");
                }
                match admit(state, index, entry.digest, Mutation::None) {
                    Verdict::Duplicate(outcome) if outcome == entry.outcome => {}
                    _ => out.push("R1 a repeated matching request does not return its result"),
                }
                let other = (entry.digest + 1) % DIGESTS;
                match admit(state, index, other, Mutation::None) {
                    Verdict::Conflict => {}
                    Verdict::BelowRetention if State::sequence(index) <= state.floor => {}
                    _ => out.push("R2 a different payload for an admitted id is not refused"),
                }
            }
            None => {
                if State::sequence(index) <= state.floor
                    && admit(state, index, 0, Mutation::None) != Verdict::BelowRetention
                {
                    out.push("R3 a forgotten request is admitted again");
                }
            }
        }
    }
    out
}

/// Every operation the model exposes, with every argument.
fn all_ops() -> Vec<Op> {
    let mut ops = Vec::new();
    for seq in 0..SEQS as usize {
        for digest in 0..DIGESTS {
            ops.push(Op::Admit { seq, digest });
            ops.push(Op::Record { seq, digest });
        }
        for outcome in [Outcome::Pending, Outcome::Accepted(1), Outcome::Rejected] {
            ops.push(Op::Settle { seq, outcome });
        }
    }
    for through in 0..=TOP_FLOOR {
        ops.push(Op::Acknowledge { through });
    }
    ops
}

struct Exploration {
    states: usize,
    transitions: usize,
    duplicates: usize,
    conflicts: usize,
    settled: usize,
    first_violation: Option<(State, Op, String)>,
    traces: HashMap<State, (State, String)>,
}

fn explore(mutation: Mutation) -> Exploration {
    let mut seen: HashSet<State> = HashSet::new();
    let mut queue: VecDeque<State> = VecDeque::new();
    let mut traces: HashMap<State, (State, String)> = HashMap::new();
    let mut transitions = 0usize;
    let mut duplicates = 0usize;
    let mut conflicts = 0usize;
    let mut settled = 0usize;
    let mut first_violation: Option<(State, Op, String)> = None;
    let ops = all_ops();

    seen.insert(State::fresh());
    queue.push_back(State::fresh());
    while let Some(state) = queue.pop_front() {
        for op in &ops {
            transitions += 1;
            if let Op::Admit { seq, digest } = *op {
                match admit(&state, seq, digest, mutation) {
                    Verdict::Duplicate(_) => duplicates += 1,
                    Verdict::Conflict => conflicts += 1,
                    _ => {}
                }
            }
            match apply(&state, *op, mutation) {
                Ok(next) => {
                    // R1 (transition half): a request that is already recorded
                    // must not be admitted as fresh. This is the rule the
                    // `DuplicateFresh` mutation breaks, and it is checked before
                    // the overwrite it would cause.
                    if let Op::Record { seq, digest } = *op
                        && state.entry[seq].is_some()
                        && admit(&state, seq, digest, mutation) == Verdict::Fresh
                    {
                        first_violation.get_or_insert((
                            state,
                            *op,
                            "R1 a repeated matching request was admitted as fresh".to_string(),
                        ));
                    }
                    if let Op::Settle { seq, .. } = *op
                        && state.entry[seq].is_some()
                    {
                        settled += 1;
                    }
                    // R4 (transition half): a settled outcome must not change,
                    // and a recorded digest must not be overwritten. Dropping an
                    // entry is legitimate only by a raised floor.
                    for index in 0..SEQS as usize {
                        let before = state.entry[index];
                        let after = next.entry[index];
                        if let (Some(before), Some(after)) = (before, after) {
                            if before.digest != after.digest {
                                first_violation.get_or_insert((
                                    state,
                                    *op,
                                    "R2 a recorded payload digest was overwritten".to_string(),
                                ));
                            }
                            if before.outcome.settled() && before.outcome != after.outcome {
                                first_violation.get_or_insert((
                                    state,
                                    *op,
                                    "R4 a settled outcome was rewritten".to_string(),
                                ));
                            }
                        }
                        if before.is_some()
                            && after.is_none()
                            && State::sequence(index) > next.floor
                        {
                            first_violation.get_or_insert((
                                state,
                                *op,
                                "R1 an outcome was dropped without a raised floor".to_string(),
                            ));
                        }
                    }
                    for violation in violations(&next) {
                        first_violation.get_or_insert((state, *op, violation.to_string()));
                    }
                    if seen.insert(next) {
                        traces.insert(next, (state, format!("{} → {:?}", op.label(), next)));
                        queue.push_back(next);
                    }
                }
                Err(_) => {
                    // A refused step must not change the state: the model returns
                    // the input unchanged by construction, like the real book's
                    // `&self` probe or a caller that only records after `Fresh`.
                }
            }
        }
    }
    Exploration {
        states: seen.len(),
        transitions,
        duplicates,
        conflicts,
        settled,
        first_violation,
        traces,
    }
}

fn witness(mut state: State, traces: &HashMap<State, (State, String)>) -> Vec<String> {
    let mut path = Vec::new();
    let mut guard = 0;
    while let Some((parent, label)) = traces.get(&state) {
        path.push(label.clone());
        state = *parent;
        guard += 1;
        if guard > 64 {
            break;
        }
    }
    path.reverse();
    path
}

#[test]
fn the_request_replay_invariant_holds_over_every_reachable_state() {
    let e = explore(Mutation::None);
    if let Some((state, op, violation)) = &e.first_violation {
        let path = witness(*state, &e.traces);
        panic!(
            "request replay invariant violated: {violation}\nafter: {path:?}\nthen: {}",
            op.label()
        );
    }
    // Coverage, not just "no failure": a search that never replayed a request,
    // never saw a conflict, or never settled one would pass vacuously.
    assert!(e.states > 10, "only {} states reached", e.states);
    assert!(
        e.duplicates > 0,
        "no repeated matching request was ever answered"
    );
    assert!(e.conflicts > 0, "no conflicting payload was ever offered");
    assert!(e.settled > 0, "no outcome was ever settled");
    println!(
        "request replay: states={} transitions={} duplicates={} conflicts={} settled={} violations=0",
        e.states, e.transitions, e.duplicates, e.conflicts, e.settled
    );
}

#[test]
fn each_replay_mutation_is_caught_with_a_witness() {
    let cases = [
        (Mutation::DuplicateFresh, "R1"),
        (Mutation::PruneRevives, "R3"),
        (Mutation::SettleAny, "R4"),
    ];
    for (mutation, expected) in cases {
        let e = explore(mutation);
        let (state, op, violation) = e
            .first_violation
            .unwrap_or_else(|| panic!("mutation {mutation:?} was not caught"));
        assert!(
            violation.starts_with(expected),
            "mutation {mutation:?}: expected {expected}, got {violation}"
        );
        let path = witness(state, &e.traces);
        println!(
            "mutation {mutation:?}: caught ({violation}) after {} step(s), last: {}",
            path.len(),
            op.label()
        );
    }
}

// ---------------------------------------------------------------------------
// Conformance: the model is a *specification*, so it must describe the real
// `AdmissionBook` and not a tidier cousin of it. Both are driven with the same
// deterministic pseudo-random sequence of legal steps, and after every step the
// verdict and the whole observable state (digest, outcome and floor) are
// compared. Unlike the fence model, the legality guard here is the model's own
// `Fresh` answer: recording a request the book has not admitted is not a
// protocol step the production path performs.
// ---------------------------------------------------------------------------

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

fn digests() -> [[u8; 32]; DIGESTS as usize] {
    [[0u8; 32], [1u8; 32]]
}

fn ids() -> [RequestId; SEQS as usize] {
    [
        RequestId::new("d21", "principal", 1, 1),
        RequestId::new("d21", "principal", 1, 2),
    ]
}

fn digest_index(bytes: &[u8; 32]) -> u8 {
    bytes[0]
}

fn model_outcome(outcome: &AdmittedOutcome) -> Outcome {
    match outcome {
        AdmittedOutcome::Pending { .. } => Outcome::Pending,
        AdmittedOutcome::Accepted { slot, .. } => Outcome::Accepted(slot.0),
        AdmittedOutcome::Rejected(_) => Outcome::Rejected,
    }
}

fn model_verdict(verdict: &AdmissionVerdict) -> Verdict {
    match verdict {
        AdmissionVerdict::Fresh => Verdict::Fresh,
        AdmissionVerdict::Duplicate(outcome) => Verdict::Duplicate(model_outcome(outcome)),
        AdmissionVerdict::Conflict { .. } => Verdict::Conflict,
        AdmissionVerdict::BelowRetention { .. } => Verdict::BelowRetention,
        other => panic!("the conformance driver reached an out-of-model verdict: {other:?}"),
    }
}

fn observe(book: &AdmissionBook, ids: &[RequestId; SEQS as usize]) -> State {
    let mut state = State::fresh();
    for (index, id) in ids.iter().enumerate() {
        state.entry[index] = book.admission(id).map(|admission| Entry {
            digest: digest_index(&admission.digest),
            outcome: model_outcome(&admission.outcome),
        });
    }
    state.floor = book.floor(&ids[0]).unwrap_or(0);
    state.known = book.floor(&ids[0]).is_some();
    state
}

fn refused() -> Refusal {
    Refusal::new(Code::BAD_JSON, "domain refusal")
}

#[test]
fn the_model_and_the_real_admission_book_agree_on_every_step() {
    let mut rng = Rng(0xD1B5_4A32_D192_ED03);
    let digests = digests();
    let ids = ids();
    let mut compared = 0usize;
    let mut replays = 0usize;

    for sequence in 0..200 {
        let mut book = AdmissionBook::new(8);
        let mut model = State::fresh();

        for turn in 0..10 {
            let seq = rng.below(SEQS) as usize;
            let digest = rng.below(DIGESTS as u64) as u8;
            // The driver prefers the admission probe, because that is what a
            // retrying client actually calls; the other steps follow it.
            let op = match rng.below(4) {
                0 => Op::Admit { seq, digest },
                1 => Op::Record { seq, digest },
                2 => Op::Settle {
                    seq,
                    outcome: if rng.below(2) == 0 {
                        Outcome::Accepted(1)
                    } else {
                        Outcome::Rejected
                    },
                },
                _ => Op::Acknowledge {
                    through: rng.below(TOP_FLOOR + 1),
                },
            };

            let verdict = match op {
                Op::Admit { seq, digest } => {
                    let modeled = admit(&model, seq, digest, Mutation::None);
                    let real = book.admit(&ids[seq], digests[digest as usize]);
                    let observed = model_verdict(&real);
                    assert_eq!(
                        modeled,
                        observed,
                        "sequence {sequence} turn {turn}: model says {modeled:?} for {}; the book says {observed:?}",
                        op.label()
                    );
                    if matches!(observed, Verdict::Duplicate(_)) {
                        replays += 1;
                    }
                    Some(observed)
                }
                _ => None,
            };

            if let Some(verdict) = verdict {
                assert!(
                    apply(&model, op, Mutation::None).is_ok(),
                    "an admission probe never fails"
                );
                // A repeated matching request is answered, not re-recorded; a
                // conflicting one is refused. Asserting the book's own answer
                // here keeps the driver from "passing" by never replaying.
                if let Verdict::Duplicate(outcome) = verdict {
                    assert!(
                        outcome.settled() || outcome == Outcome::Pending,
                        "a replayed result must be the recorded outcome"
                    );
                }
            } else {
                let legal = match op {
                    Op::Record { seq, digest } => {
                        admit(&model, seq, digest, Mutation::None) == Verdict::Fresh
                    }
                    Op::Settle { seq, .. } => model.entry[seq]
                        .map(|entry| !entry.outcome.settled())
                        .unwrap_or(false),
                    Op::Acknowledge { .. } => true,
                    Op::Admit { .. } => unreachable!(),
                };
                if legal {
                    // The model's step must be accepted whenever the driver
                    // performs the corresponding real step.
                    let next = apply(&model, op, Mutation::None)
                        .unwrap_or_else(|error| panic!("legal step refused by the model: {error}"));
                    match op {
                        Op::Record { seq, digest } => {
                            book.record(&ids[seq], SubmissionId(7), digests[digest as usize]);
                        }
                        Op::Settle { seq, outcome } => {
                            let outcome = match outcome {
                                Outcome::Accepted(slot) => AdmittedOutcome::Accepted {
                                    submission: SubmissionId(7),
                                    slot: Slot(slot),
                                },
                                Outcome::Rejected => AdmittedOutcome::Rejected(refused()),
                                Outcome::Pending => AdmittedOutcome::Pending {
                                    submission: SubmissionId(7),
                                },
                            };
                            book.settle(&ids[seq], outcome);
                        }
                        Op::Acknowledge { through } => {
                            book.acknowledge(&ids[seq], through);
                        }
                        Op::Admit { .. } => unreachable!(),
                    }
                    model = next;
                }
            }

            // Whole-state equality, not just the verdict: digest, outcome and
            // floor must agree after every step.
            assert_eq!(
                model,
                observe(&book, &ids),
                "sequence {sequence} turn {turn}: state diverged after {}",
                op.label()
            );
            if let Some(violation) = violations(&model).first() {
                panic!("model invariant violated in conformance run: {violation}");
            }
            compared += 1;
        }
    }
    assert!(replays > 0, "no repeated request was ever replayed");
    println!(
        "replay conformance: {compared} steps compared, 0 disagreements, {replays} replays answered"
    );
}

// D21 (second claim): "the authority epoch never decreases", as a
// machine-checked finite model rather than a prose argument about it.
//
// THE CLAIM. A partitioned leader that missed a leadership change must not be
// able to take a resource back under its old authority. Written as the things
// this file checks, over the committed fence and the takeover transition:
//
//   (E1) A takeover is accepted only under an epoch *strictly greater* than the
//        one the committed state holds; an equal or older authority is refused
//        and changes nothing.
//   (E2) No accepted transition lowers a resource's committed epoch. A
//        generation advance keeps the epoch; a takeover raises it.
//   (E3) Every committed fence has an epoch of at least 1: authority is never
//        issued at epoch 0.
//   (E4) A takeover installs generation 1 at the new epoch (a fresh authority
//        does not inherit the previous holder's generation).
//
// WHAT KIND OF CHECK THIS IS, AND WHAT IT IS NOT. The state below abstracts
// `JobQueue`/`FenceTable`: one resource, two holders, four job states, and a
// finite epoch/generation space. Every reachable state is generated by
// breadth-first search from the empty queue, and every transition out of every
// reachable state is checked, so this covers **all runs of the abstraction**,
// not samples. The real takeover rule is a compare-and-swap on `epoch`; the
// abstraction keeps exactly that comparison and drops the payload.
//
// What this does **not** do is prove the claim for an unbounded state space by
// induction in a proof assistant. D21's symbolic MM0/Lean induction remains
// open and is named as such in the execution record. This file is the finite
// model, its guard mutations, and a differential check against the real
// `JobQueue`.
//
// GUARD MUTATIONS. A checker that cannot fail proves nothing. Each mutation of
// the model's *rules* must produce a counterexample witness: accepting an equal
// epoch (E1), rolling the installed epoch back below the current one (E2), and
// wrapping the epoch at the top of the space (E2), and inheriting the previous
// generation on takeover (E4).

use std::collections::{HashMap, HashSet, VecDeque};

use unfer_consensus::jobs::{Fence, JobQueue, JobState};

const HOLDERS: [&str; 2] = ["w0", "w1"];
const RESOURCE: &str = "r0";
/// The top of the abstracted epoch space; reaching it exercises the
/// generation-advance rule.
const TOP_EPOCH: u64 = 4;
/// The top of the abstracted generation space.
const MAX_GEN: u64 = 2;
/// The highest takeover epoch the model proposes.
const TOP_PROPOSAL: u64 = 4;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Pos {
    epoch: u64,
    generation: u64,
}

impl Pos {
    fn first() -> Self {
        Pos {
            epoch: 1,
            generation: 1,
        }
    }
}

/// `FenceTable`'s successor rule (`next_position`), with the abstracted tops
/// standing in for `u64::MAX`. The wrap mutation is here because the epoch rule
/// is exactly what it breaks.
fn next_pos(pos: Pos, epoch_top: u64, generation_top: u64, mutation: Mutation) -> Option<Pos> {
    if pos.generation < generation_top {
        Some(Pos {
            epoch: pos.epoch,
            generation: pos.generation + 1,
        })
    } else if pos.epoch < epoch_top {
        Some(Pos {
            epoch: pos.epoch + 1,
            generation: 1,
        })
    } else if mutation == Mutation::EpochWrapAtTop {
        // The bug this models: at the top of the space the epoch wraps to 0, so
        // every later fence is older than the one a sink has already passed.
        Some(Pos {
            epoch: 0,
            generation: 1,
        })
    } else {
        None
    }
}

/// How a rule is bent by a guard mutation. `None` is the model as the code
/// describes it; each variant deliberately breaks one rule so the checker has
/// to notice.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mutation {
    None,
    /// A takeover accepts an epoch equal to the current one.
    EqualEpochTakeOver,
    /// A takeover installs an epoch below the one the state holds.
    EpochRollback,
    /// A full epoch space wraps to 0 instead of refusing.
    EpochWrapAtTop,
    /// A takeover installs the previous holder's generation instead of 1.
    TakeOverGeneration,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Job {
    Queued,
    Claimed,
    Fired,
    Disabled,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct State {
    fence: Option<Pos>,
    holder: Option<usize>,
    released: bool,
    job: Job,
}

impl State {
    fn fresh() -> Self {
        State {
            fence: None,
            holder: None,
            released: false,
            job: Job::Queued,
        }
    }

    fn held(&self) -> bool {
        self.fence.is_some() && !self.released
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Op {
    Claim,
    Renew,
    Release,
    Settle,
    Disable,
    TakeOver { epoch: u64 },
}

impl Op {
    fn label(self) -> String {
        match self {
            Op::Claim => "claim".to_string(),
            Op::Renew => "renew".to_string(),
            Op::Release => "release".to_string(),
            Op::Settle => "settle".to_string(),
            Op::Disable => "disable".to_string(),
            Op::TakeOver { epoch } => format!("take over at epoch {epoch}"),
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Step {
    op: Op,
    holder: usize,
    presented: Option<Pos>,
}

impl Step {
    fn label(&self) -> String {
        format!(
            "{} as {} under {}",
            self.op.label(),
            HOLDERS[self.holder],
            match self.presented {
                Some(pos) => format!("(epoch {}, generation {})", pos.epoch, pos.generation),
                None => "no fence".to_string(),
            }
        )
    }
}

/// The takeover target epoch, or a refusal. This is the compare-and-swap the
/// claim is about: the new authority must *strictly* supersede the current one.
fn takeover_target(
    current: Option<Pos>,
    proposed: u64,
    mutation: Mutation,
) -> Result<u64, &'static str> {
    let current_epoch = current.map(|pos| pos.epoch).unwrap_or(0);
    match mutation {
        Mutation::EqualEpochTakeOver if proposed == current_epoch => Ok(proposed),
        // The bug this models: an accepted takeover installs the *previous*
        // authority epoch instead of the new leader's. The first takeover has no
        // previous epoch, so it behaves correctly and the bug is witnessed on a
        // later leadership change rather than at initialization.
        Mutation::EpochRollback if current.is_some() => Ok(current_epoch.saturating_sub(1)),
        _ if proposed > current_epoch => Ok(proposed),
        _ => Err("STALE_EPOCH"),
    }
}

/// The spec: `FenceTable` + `JobQueue`'s rules, written independently of the
/// implementation so a divergence is a disagreement between two programs rather
/// than a program agreeing with itself.
fn apply_op(
    state: &State,
    step: &Step,
    mutation: Mutation,
    epoch_top: u64,
    generation_top: u64,
) -> Result<State, &'static str> {
    let mut next = *state;
    match step.op {
        Op::Claim => {
            if state.held() {
                return Err("RESOURCE_HELD");
            }
            if state.job != Job::Queued {
                return Err("JOB_NOT_QUEUED");
            }
            let pos = match state.fence {
                None => Pos::first(),
                Some(current) => next_pos(current, epoch_top, generation_top, mutation)
                    .ok_or("FENCE_EXHAUSTED")?,
            };
            next.fence = Some(pos);
            next.holder = Some(step.holder);
            next.released = false;
            next.job = Job::Claimed;
        }
        Op::Renew => {
            if !current_claim(state, step) {
                return Err("STALE_FENCE");
            }
            let current = state.fence.expect("a claim holds a fence");
            next.fence = Some(
                next_pos(current, epoch_top, generation_top, mutation).ok_or("FENCE_EXHAUSTED")?,
            );
            next.released = false;
        }
        Op::Release => {
            if !current_claim(state, step) {
                return Err("STALE_FENCE");
            }
            next.holder = None;
            next.released = true;
            next.job = Job::Queued;
        }
        Op::Settle => {
            if !current_claim(state, step) {
                return Err("STALE_FENCE");
            }
            // The effect is applied and recorded under the current fence, so its
            // epoch is the committed authority epoch at that moment.
            let Some(applied) = step.presented else {
                return Err("NO_FENCE");
            };
            let held = state.fence.expect("a claim holds a fence");
            if applied != held {
                return Err("APPLIED_UNDER_NON_CURRENT_FENCE");
            }
            next.holder = None;
            next.released = true;
            next.job = Job::Fired;
        }
        Op::Disable => {
            if !current_claim(state, step) {
                return Err("STALE_FENCE");
            }
            next.holder = None;
            next.released = true;
            next.job = Job::Disabled;
        }
        Op::TakeOver { epoch } => {
            if matches!(state.job, Job::Fired | Job::Disabled) {
                return Err("JOB_NOT_CLAIMABLE");
            }
            let target = takeover_target(state.fence, epoch, mutation)?;
            let generation = match mutation {
                Mutation::TakeOverGeneration => state.fence.map(|pos| pos.generation).unwrap_or(0),
                _ => 1,
            };
            next.fence = Some(Pos {
                epoch: target,
                generation,
            });
            next.holder = Some(step.holder);
            next.released = false;
            next.job = Job::Claimed;
        }
    }
    Ok(next)
}

/// The guard every mutating operation except takeover asks: a live claim under
/// the fence the caller presents.
fn current_claim(state: &State, step: &Step) -> bool {
    state.job == Job::Claimed
        && state.fence.is_some()
        && state.fence == step.presented
        && !state.released
}

/// The state invariants (E3 and the lifecycle agreement).
fn violations(state: &State) -> Vec<&'static str> {
    let mut out = Vec::new();
    if let Some(fence) = state.fence {
        if fence.epoch == 0 {
            out.push("E3 a committed fence has epoch 0");
        }
    } else if state.released {
        out.push("E3 a released resource has no fence");
    }
    let claimed = state.job == Job::Claimed;
    if claimed != (state.holder.is_some() && !state.released) {
        out.push("E3 the job state disagrees with the fence");
    }
    out
}

fn all_presented() -> Vec<Option<Pos>> {
    let mut out: Vec<Option<Pos>> = Vec::new();
    for epoch in 1..=TOP_EPOCH {
        for generation in 1..=MAX_GEN {
            out.push(Some(Pos { epoch, generation }));
        }
    }
    out.push(None);
    out
}

fn all_steps() -> Vec<Step> {
    let mut ops = vec![Op::Claim, Op::Renew, Op::Release, Op::Settle, Op::Disable];
    // Authority epochs start at 1 (`Pos::first`), so a takeover never proposes
    // epoch 0; proposing it would only exercise the model's refusal of a
    // non-authority, not the monotonicity claim.
    for epoch in 1..=TOP_PROPOSAL {
        ops.push(Op::TakeOver { epoch });
    }
    let mut steps = Vec::new();
    for holder in 0..HOLDERS.len() {
        for op in &ops {
            // A takeover names an epoch, not a presented fence.
            if matches!(op, Op::TakeOver { .. }) {
                steps.push(Step {
                    op: *op,
                    holder,
                    presented: None,
                });
                continue;
            }
            for presented in &all_presented() {
                steps.push(Step {
                    op: *op,
                    holder,
                    presented: *presented,
                });
            }
        }
    }
    steps
}

struct Exploration {
    states: usize,
    transitions: usize,
    accepted: usize,
    refused: usize,
    effects: usize,
    first_violation: Option<(State, Step, &'static str)>,
    traces: HashMap<State, (State, String)>,
}

fn explore(mutation: Mutation) -> Exploration {
    let mut seen: HashSet<State> = HashSet::new();
    let mut queue: VecDeque<State> = VecDeque::new();
    let mut traces: HashMap<State, (State, String)> = HashMap::new();
    let mut transitions = 0usize;
    let mut accepted = 0usize;
    let mut refused = 0usize;
    let mut effects = 0usize;
    let mut first_violation = None;
    let steps = all_steps();

    seen.insert(State::fresh());
    queue.push_back(State::fresh());
    while let Some(state) = queue.pop_front() {
        for step in &steps {
            transitions += 1;
            let outcome = apply_op(&state, step, mutation, TOP_EPOCH, MAX_GEN);
            let is_takeover = matches!(step.op, Op::TakeOver { .. });
            match &outcome {
                Ok(next) => {
                    if is_takeover {
                        accepted += 1;
                    }
                    if matches!(step.op, Op::Settle) {
                        effects += 1;
                    }
                    // E2 (transition half): no accepted transition lowers the
                    // committed epoch. Checked before E1 so a rollback is
                    // witnessed by the invariant it actually breaks.
                    if let (Some(before), Some(after)) = (state.fence, next.fence)
                        && after.epoch < before.epoch
                    {
                        first_violation.get_or_insert((
                            state,
                            *step,
                            "E2 an accepted transition lowered the committed epoch",
                        ));
                    }
                    // E1 (transition half): an accepted takeover issues an epoch
                    // strictly greater than the one it replaces.
                    if is_takeover && let Op::TakeOver { epoch } = step.op {
                        let before = state.fence.map(|pos| pos.epoch);
                        let after = next.fence.expect("takeover installs a fence");
                        if let Some(before) = before
                            && after.epoch <= before
                        {
                            first_violation.get_or_insert((
                                state,
                                *step,
                                "E1 a takeover was accepted under a non-superseding epoch",
                            ));
                        }
                        if after.epoch != epoch {
                            first_violation.get_or_insert((
                                state,
                                *step,
                                "E1 a takeover installed an epoch other than the proposed one",
                            ));
                        }
                        // E4 (transition half): fresh authority starts at
                        // generation 1.
                        if after.generation != 1 {
                            first_violation.get_or_insert((
                                state,
                                *step,
                                "E4 a takeover inherited the previous generation",
                            ));
                        }
                    }
                    for violation in violations(next) {
                        first_violation.get_or_insert((state, *step, violation));
                    }
                    if seen.insert(*next) {
                        traces.insert(*next, (state, format!("{} → {:?}", step.label(), next)));
                        queue.push_back(*next);
                    }
                }
                Err(_) => {
                    if is_takeover {
                        refused += 1;
                    }
                    // A refused transition changes nothing by construction: the
                    // model returns the input, which is what the caller sees.
                }
            }
        }
    }
    Exploration {
        states: seen.len(),
        transitions,
        accepted,
        refused,
        effects,
        first_violation,
        traces,
    }
}

fn witness(mut state: State, traces: &HashMap<State, (State, String)>) -> Vec<String> {
    let mut path = Vec::new();
    let mut guard = 0;
    while let Some((parent, label)) = traces.get(&state) {
        path.push(label.clone());
        state = *parent;
        guard += 1;
        if guard > 64 {
            break;
        }
    }
    path.reverse();
    path
}

#[test]
fn the_authority_epoch_never_decreases_over_every_reachable_state() {
    let e = explore(Mutation::None);
    if let Some((state, step, violation)) = &e.first_violation {
        let path = witness(*state, &e.traces);
        panic!(
            "epoch invariant violated: {violation}\nafter: {path:?}\nthen: {}",
            step.label()
        );
    }
    // Coverage, not just "no failure": a search that never accepted a takeover,
    // never refused an older authority, or never settled an effect would pass
    // vacuously.
    assert!(e.states > 10, "only {} states reached", e.states);
    assert!(e.accepted > 0, "no takeover was ever accepted");
    assert!(e.refused > 0, "no stale authority was ever offered");
    assert!(e.effects > 0, "no effect was ever settled");
    println!(
        "epoch invariant: states={} transitions={} takeovers_accepted={} takeovers_refused={} effects={} violations=0",
        e.states, e.transitions, e.accepted, e.refused, e.effects
    );
}

#[test]
fn each_epoch_mutation_is_caught_with_a_witness() {
    let cases = [
        (Mutation::EqualEpochTakeOver, "E1"),
        (Mutation::EpochRollback, "E2"),
        (Mutation::EpochWrapAtTop, "E2"),
        (Mutation::TakeOverGeneration, "E4"),
    ];
    for (mutation, expected) in cases {
        let e = explore(mutation);
        let (state, step, violation) = e
            .first_violation
            .unwrap_or_else(|| panic!("mutation {mutation:?} was not caught"));
        assert!(
            violation.starts_with(expected),
            "mutation {mutation:?}: expected {expected}, got {violation}"
        );
        let path = witness(state, &e.traces);
        println!(
            "mutation {mutation:?}: caught ({violation}) after {} step(s), last: {}",
            path.len(),
            step.label()
        );
    }
}

// ---------------------------------------------------------------------------
// Conformance: drive the real `JobQueue` and the model with the same legal
// steps, and compare the accept/refuse answer and the whole observable state
// (fence, holder, released, job) after every step. The model's finite tops are
// an abstraction, so the driver passes `u64::MAX` for both, exactly as the real
// `next_position` behaves; the model check above passes the small tops.
// ---------------------------------------------------------------------------

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

fn model_job(state: Option<JobState>) -> Job {
    match state {
        Some(JobState::Queued) | None => Job::Queued,
        Some(JobState::Claimed) => Job::Claimed,
        Some(JobState::Fired) => Job::Fired,
        Some(JobState::Disabled) => Job::Disabled,
    }
}

fn holder_index(queue: &JobQueue) -> Option<usize> {
    queue
        .fences()
        .holder(RESOURCE)
        .and_then(|holder| HOLDERS.iter().position(|known| *known == holder))
}

fn observe(queue: &JobQueue) -> State {
    State {
        fence: queue.current_fence(RESOURCE).map(|fence| Pos {
            epoch: fence.epoch,
            generation: fence.generation,
        }),
        holder: holder_index(queue),
        released: queue.fences().is_released(RESOURCE),
        job: model_job(queue.state(RESOURCE)),
    }
}

fn real_fence(pos: Pos) -> Fence {
    Fence::new("d21-epoch", RESOURCE, pos.epoch, pos.generation)
}

/// The real call shape for operations that require a presented fence. A missing
/// fence is a refusal, exactly as it is in the model.
fn with_fence(
    presented: Option<Pos>,
    call: impl FnOnce(&Fence) -> Result<(), unfer_protocol::Diagnostic>,
) -> Result<(), unfer_protocol::Diagnostic> {
    match presented {
        Some(pos) => call(&real_fence(pos)),
        None => Err(unfer_protocol::Diagnostic::new(
            unfer_protocol::Code::CALL_DENIED,
            "no fence presented".to_string(),
            unfer_protocol::Severity::Error,
        )),
    }
}

#[test]
fn the_model_and_the_real_job_queue_agree_on_every_step() {
    let mut rng = Rng(0xE9_0C_1A_7B_5D_44_2F_11);
    let mut compared = 0usize;
    let mut accepted = 0usize;
    let mut refused = 0usize;
    let mut epoch_advances = 0usize;

    for sequence in 0..150 {
        let mut queue = JobQueue::with_deployment("d21-epoch");
        queue.enqueue(RESOURCE);
        let mut model = State::fresh();
        let mut previous_epoch = 0u64;

        for turn in 0..24 {
            let op = match rng.below(10) {
                0 | 1 => Op::Claim,
                2 => Op::Renew,
                3 => Op::Release,
                4 => Op::Settle,
                5 => Op::Disable,
                _ => Op::TakeOver {
                    epoch: rng.below(TOP_PROPOSAL + 1),
                },
            };
            let holder = rng.below(HOLDERS.len() as u64) as usize;
            let presented = model.fence.filter(|_| rng.below(2) == 0);
            let step = Step {
                op,
                holder,
                presented,
            };

            // One output shape for both programs: Ok(new state) or a refusal.
            let (model_result, real_result) = match op {
                Op::Claim => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    queue
                        .claim_in("d21-epoch", RESOURCE, HOLDERS[holder])
                        .map(|_| ()),
                ),
                Op::Renew => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    with_fence(presented, |fence| {
                        queue.renew_at(RESOURCE, fence).map(|_| ())
                    }),
                ),
                Op::Release => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    with_fence(presented, |fence| queue.unclaim_at(RESOURCE, fence)),
                ),
                Op::Settle => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    with_fence(presented, |fence| queue.mark_fired_at(RESOURCE, fence)),
                ),
                Op::Disable => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    with_fence(presented, |fence| queue.disable_at(RESOURCE, fence)),
                ),
                Op::TakeOver { epoch } => (
                    apply_op(&model, &step, Mutation::None, u64::MAX, u64::MAX),
                    queue
                        .take_over(RESOURCE, epoch, HOLDERS[holder])
                        .map(|_| ()),
                ),
            };

            assert_eq!(
                model_result.is_ok(),
                real_result.is_ok(),
                "sequence {sequence} turn {turn}: model and queue disagree on {} \
                 (model {:?}, queue {:?})",
                step.label(),
                model_result.as_ref().err(),
                real_result.as_ref().err(),
            );
            if matches!(op, Op::TakeOver { .. }) {
                if model_result.is_ok() {
                    accepted += 1;
                } else {
                    refused += 1;
                }
            }
            if let Ok(next) = model_result {
                model = next;
            }

            assert_eq!(
                model,
                observe(&queue),
                "sequence {sequence} turn {turn}: state diverged after {}",
                step.label()
            );
            let observed_epoch = model.fence.map(|pos| pos.epoch).unwrap_or(0);
            assert!(
                observed_epoch >= previous_epoch,
                "sequence {sequence} turn {turn}: committed epoch fell from \
                 {previous_epoch} to {observed_epoch}"
            );
            if observed_epoch > previous_epoch {
                epoch_advances += 1;
            }
            previous_epoch = observed_epoch;
            if let Some(violation) = violations(&model).first() {
                panic!("model invariant violated in conformance run: {violation}");
            }
            compared += 1;
        }
    }
    assert!(accepted > 0, "no takeover was ever accepted");
    assert!(refused > 0, "no stale authority was ever refused");
    assert!(epoch_advances > 0, "the committed epoch never advanced");
    println!(
        "epoch conformance: {compared} steps compared, 0 disagreements, {accepted} takeovers accepted, {refused} refused, {epoch_advances} epoch advances"
    );
}

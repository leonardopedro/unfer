// D21 (first target): machine-check the D14 fencing invariant over the fence
// state, not over a prose argument about it.
//
// THE CLAIM. D14's acceptance is one sentence: *only the current fence can settle
// the job or mutate its protected resource*. Written as the thing this file
// checks:
//
//   (I1) A settle that applies an effect presents the fence the state holds for
//        that resource at that moment, and the fence recorded with the effect is
//        that same fence.
//   (I2) Every fence the state issues for a resource is strictly newer than the
//        one before it — so "current" is a total order a sink can rely on, and a
//        released-and-reclaimed resource never hands out a fence a sink has
//        already passed.
//   (I3) The job lifecycle agrees with the fence: `Claimed` exactly when a holder
//        holds an unreleased fence.
//
// WHAT KIND OF CHECK THIS IS, AND WHAT IT IS NOT. The state below is an
// abstraction of `FenceTable`/`JobQueue`: two resources, two holders, and a
// *finite* generation space (1..=3, with the epoch advancing at the top, exactly
// as `next_position` does). Every reachable state of that abstraction is
// generated by breadth-first search from `init`, and every transition out of
// every reachable state is checked. Because the explored set is closed under the
// transition relation, this covers **all runs of the abstraction**, not samples
// and not "up to depth N".
//
// The finite generation space is an abstraction, and the three claims do not
// depend on its size: `next_position` only ever increments, the ordering claim is
// about the relation between two consecutive positions, and the identity claim
// compares fences for equality. The epoch/generation *arithmetic* (`u64`
// overflow at the very top) is checked separately in `jobs.rs`'s own tests; the
// abstraction here checks the rules, not the width.
//
// What this does **not** do is prove the claims for an unbounded state space by
// induction in a proof assistant. D21's symbolic MM0/Lean induction remains open
// and is named in the execution record as the reviewed subtask; this file is the
// machine-checked finite model, its guard mutations, and a differential check
// against the real `JobQueue`.
//
// GUARD MUTATIONS. A checker that cannot fail proves nothing. Three mutations of
// the model's *rules* (not the code under test) must each produce a counterexample
// witness: settling on a non-current fence, wrapping the generation instead of
// advancing the epoch, and releasing on a stale fence. Each witness is printed and
// asserted to violate a named invariant.

use std::collections::{BTreeSet, HashMap, HashSet, VecDeque};

use unfer_consensus::jobs::{Fence, JobQueue, JobState};

const RESOURCES: [&str; 2] = ["r0", "r1"];
const HOLDERS: [&str; 2] = ["w0", "w1"];
/// The top of the abstracted generation space. Reaching it exercises the
/// epoch-advance rule exactly once per pass through the space.
const MAX_GEN: u64 = 3;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Pos {
    epoch: u64,
    generation: u64,
}

impl Pos {
    fn first() -> Self {
        Pos {
            epoch: 1,
            generation: 1,
        }
    }
}

/// `FenceTable`'s successor rule (`next_position`), with the abstracted top of
/// the space standing in for `u64::MAX`. The mutation hook is here because the
/// epoch-advance rule is exactly what the wrap mutation breaks.
fn next_pos(pos: Pos, top: u64, mutation: Mutation) -> Option<Pos> {
    if pos.generation < top {
        Some(Pos {
            epoch: pos.epoch,
            generation: pos.generation + 1,
        })
    } else if mutation == Mutation::WrapGeneration {
        // The bug this models: a wrap hands out a fence that sorts *below* the
        // current one, so a sink that has already passed it treats every later
        // effect as stale forever.
        Some(Pos {
            epoch: pos.epoch,
            generation: 0,
        })
    } else if pos.epoch < top {
        Some(Pos {
            epoch: pos.epoch + 1,
            generation: 1,
        })
    } else {
        None
    }
}

/// How a rule is bent by a guard mutation. `None` is the model as the code
/// describes it; each variant deliberately breaks one rule so the checker has to
/// notice.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mutation {
    None,
    /// Settle and fire do not compare the presented fence with the current one.
    StaleSettle,
    /// A full generation space wraps to generation 0 in the same epoch.
    WrapGeneration,
    /// Release accepts a fence that is not current.
    StaleRelease,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Job {
    Queued,
    Claimed,
    Fired,
    Disabled,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Res {
    fence: Option<Pos>,
    holder: Option<usize>,
    released: bool,
    job: Job,
}

impl Res {
    fn fresh() -> Self {
        Res {
            fence: None,
            holder: None,
            released: false,
            job: Job::Queued,
        }
    }

    fn held(&self) -> bool {
        self.fence.is_some() && !self.released
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct State {
    res: [Res; 2],
}

impl State {
    fn init() -> Self {
        State {
            res: [Res::fresh(), Res::fresh()],
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
enum Op {
    Claim,
    Renew,
    Reclaim,
    Release,
    Settle,
    Disable,
}

impl Op {
    const ALL: [Op; 6] = [
        Op::Claim,
        Op::Renew,
        Op::Reclaim,
        Op::Release,
        Op::Settle,
        Op::Disable,
    ];

    fn label(self) -> &'static str {
        match self {
            Op::Claim => "claim",
            Op::Renew => "renew",
            Op::Reclaim => "reclaim",
            Op::Release => "release",
            Op::Settle => "settle",
            Op::Disable => "disable",
        }
    }
}

/// One attempted transition: the operation, the resource, the worker, and the
/// fence that worker presents. A worker can present any fence in the space — that
/// is how a stale worker's late result is modeled — but only the current one may
/// be accepted.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
struct Step {
    op: Op,
    resource: usize,
    holder: usize,
    presented: Option<Pos>,
}

impl Step {
    fn label(&self) -> String {
        format!(
            "{} {} as {} under {}",
            self.op.label(),
            RESOURCES[self.resource],
            HOLDERS[self.holder],
            match self.presented {
                Some(p) => format!("(epoch {}, generation {})", p.epoch, p.generation),
                None => "no fence".to_string(),
            }
        )
    }
}

/// The spec: `FenceTable` + `JobQueue`'s rules, written independently of the
/// implementation so a divergence is a disagreement between two programs rather
/// than a program agreeing with itself.
fn apply_op(
    state: &State,
    step: &Step,
    mutation: Mutation,
    top: u64,
) -> Result<State, &'static str> {
    let mut next = *state;
    let res = &mut next.res[step.resource];
    match step.op {
        Op::Claim => {
            if res.held() {
                return Err("RESOURCE_HELD");
            }
            let pos = match res.fence {
                None => Pos::first(),
                Some(current) => next_pos(current, top, mutation).ok_or("FENCE_EXHAUSTED")?,
            };
            if res.job != Job::Queued {
                return Err("JOB_NOT_QUEUED");
            }
            res.fence = Some(pos);
            res.holder = Some(step.holder);
            res.released = false;
            res.job = Job::Claimed;
        }
        Op::Renew => {
            if !current_claim(state, step, mutation) {
                return Err("STALE_FENCE");
            }
            let current = res.fence.expect("current claim has a fence");
            let pos = next_pos(current, top, mutation).ok_or("FENCE_EXHAUSTED")?;
            res.fence = Some(pos);
            res.released = false;
        }
        Op::Reclaim => {
            if res.held() {
                return Err("RESOURCE_HELD");
            }
            let pos = match res.fence {
                None => Pos::first(),
                Some(current) => next_pos(current, top, mutation).ok_or("FENCE_EXHAUSTED")?,
            };
            if res.job != Job::Queued {
                return Err("JOB_NOT_QUEUED");
            }
            res.fence = Some(pos);
            res.holder = Some(step.holder);
            res.released = false;
            res.job = Job::Claimed;
        }
        Op::Release => {
            if !current_claim(state, step, mutation) {
                return Err("STALE_FENCE");
            }
            res.holder = None;
            res.released = true;
            res.job = Job::Queued;
        }
        Op::Settle => {
            if !current_claim(state, step, mutation) {
                return Err("STALE_FENCE");
            }
            // The effect is applied under the presented fence, and the fence the
            // state holds is still that fence when the settle is recorded.
            let Some(applied) = step.presented else {
                return Err("NO_FENCE");
            };
            let held = res.fence.expect("a claim holds a fence");
            if applied != held {
                return Err("APPLIED_UNDER_NON_CURRENT_FENCE");
            }
            res.holder = None;
            res.released = true;
            res.job = Job::Fired;
        }
        Op::Disable => {
            if !current_claim(state, step, mutation) {
                return Err("STALE_FENCE");
            }
            res.holder = None;
            res.released = true;
            res.job = Job::Disabled;
        }
    }
    Ok(next)
}

/// The guard every mutating operation asks: a live claim, under the fence the
/// caller presents, on this resource.
fn current_claim(state: &State, step: &Step, mutation: Mutation) -> bool {
    let res = &state.res[step.resource];
    if res.job != Job::Claimed {
        return false;
    }
    match mutation {
        Mutation::StaleRelease if step.op == Op::Release => true,
        Mutation::StaleSettle if matches!(step.op, Op::Settle | Op::Disable) => true,
        _ => res.fence.is_some() && res.fence == step.presented && !res.released,
    }
}

/// Which of the three claims a state violates, if any.
fn violations(state: &State) -> Vec<&'static str> {
    let mut out = Vec::new();
    for res in &state.res {
        // I3: the lifecycle agrees with the fence.
        let claimed = res.job == Job::Claimed;
        if claimed != (res.holder.is_some() && !res.released) {
            out.push("I3 job state disagrees with the fence");
        }
        // I2 (state half): a released fence is not re-issued below itself; every
        // issued fence exists and a released one is the one that was released.
        if res.fence.is_none() && res.released {
            out.push("I2 released resource with no fence");
        }
        if res.fence.is_none() && res.job != Job::Queued {
            out.push("I3 a job left the queue without a fence");
        }
    }
    out
}

fn all_presented() -> Vec<Option<Pos>> {
    let mut out: Vec<Option<Pos>> = Vec::new();
    for epoch in 1..=MAX_GEN {
        for generation in 1..=MAX_GEN {
            out.push(Some(Pos { epoch, generation }));
        }
    }
    out.push(None);
    out
}

/// Exhaustive exploration of the abstraction. Returns every reachable state, the
/// number of transitions checked, and the first state/step that broke a claim.
struct Exploration {
    states: usize,
    transitions: usize,
    applied_effects: usize,
    first_violation: Option<(State, Step, &'static str)>,
    traces: HashMap<State, (State, String)>,
}

fn explore(mutation: Mutation) -> Exploration {
    let mut seen: HashSet<State> = HashSet::new();
    let mut queue: VecDeque<State> = VecDeque::new();
    let mut traces: HashMap<State, (State, String)> = HashMap::new();
    let mut transitions = 0usize;
    let mut applied = 0usize;
    let mut first_violation = None;
    let presented = all_presented();

    seen.insert(State::init());
    queue.push_back(State::init());
    while let Some(state) = queue.pop_front() {
        for resource in 0..RESOURCES.len() {
            for holder in 0..HOLDERS.len() {
                for op in Op::ALL {
                    for p in &presented {
                        let step = Step {
                            op,
                            resource,
                            holder,
                            presented: *p,
                        };
                        transitions += 1;
                        let outcome = apply_op(&state, &step, mutation, MAX_GEN);
                        if let Ok(next) = &outcome {
                            // I2 (transition half): a newly issued fence is
                            // strictly newer than the one it replaces.
                            let before = state.res[resource].fence;
                            let after = next.res[resource].fence;
                            if after != before
                                && let (Some(a), Some(b)) = (after, before)
                                && a <= b
                            {
                                first_violation.get_or_insert((
                                    state,
                                    step,
                                    "I2 a newly issued fence is not newer",
                                ));
                            }
                        }
                        match &outcome {
                            Ok(next) => {
                                // Only the current fence mutates the claim: a
                                // renewal, release or disable accepted under any
                                // other fence is the stale-holder bug.
                                if matches!(op, Op::Renew | Op::Release | Op::Disable)
                                    && step.presented != state.res[resource].fence
                                {
                                    first_violation.get_or_insert((
                                        state,
                                        step,
                                        "I3 a fence transition was accepted on a non-current fence",
                                    ));
                                }
                                if op == Op::Settle {
                                    applied += 1;
                                }
                                for v in violations(next) {
                                    first_violation.get_or_insert((state, step, v));
                                }
                                if seen.insert(*next) {
                                    traces.insert(
                                        *next,
                                        (state, format!("{} → {:?}", step.label(), next)),
                                    );
                                    queue.push_back(*next);
                                }
                            }
                            Err(reason) => {
                                // A refused step must not change the state: the
                                // implementation clones and rolls back, and the
                                // model returns the input unchanged by construction.
                                if *reason == "APPLIED_UNDER_NON_CURRENT_FENCE" {
                                    first_violation.get_or_insert((
                                        state,
                                        step,
                                        "I1 an effect would be applied under a non-current fence",
                                    ));
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    Exploration {
        states: seen.len(),
        transitions,
        applied_effects: applied,
        first_violation,
        traces,
    }
}

fn witness(mut state: State, traces: &HashMap<State, (State, String)>) -> Vec<String> {
    let mut path = Vec::new();
    let mut guard = 0;
    while let Some((parent, label)) = traces.get(&state) {
        path.push(label.clone());
        state = *parent;
        guard += 1;
        if guard > 64 {
            break;
        }
    }
    path.reverse();
    path
}

#[test]
fn the_fence_invariant_holds_over_every_reachable_state() {
    let e = explore(Mutation::None);
    if let Some((state, step, violation)) = &e.first_violation {
        let path = witness(*state, &e.traces);
        panic!(
            "fence invariant violated: {violation}\nafter: {path:?}\nthen: {}",
            step.label()
        );
    }
    // Coverage, not just "no failure": a search that never applied an effect or
    // never reached a released/reclaimed resource would pass vacuously.
    assert!(e.states > 100, "only {} states reached", e.states);
    assert!(e.applied_effects > 0, "no settle was ever accepted");
    println!(
        "fence invariant: states={} transitions={} settled={} violations=0",
        e.states, e.transitions, e.applied_effects
    );
}

#[test]
fn each_guard_mutation_is_caught_with_a_witness() {
    let cases = [
        (Mutation::StaleSettle, "I1"),
        (Mutation::WrapGeneration, "I2"),
        (Mutation::StaleRelease, "I3"),
    ];
    for (mutation, expected) in cases {
        let e = explore(mutation);
        let (state, step, violation) = e
            .first_violation
            .unwrap_or_else(|| panic!("mutation {mutation:?} was not caught"));
        assert!(
            violation.starts_with(expected),
            "mutation {mutation:?}: expected {expected}, got {violation}"
        );
        let path = witness(state, &e.traces);
        println!(
            "mutation {mutation:?}: caught ({violation}) after {} step(s), last: {}",
            path.len(),
            step.label()
        );
        assert!(
            !path.is_empty() || step.op != Op::Claim,
            "a counterexample should come with a trace"
        );
    }
}

// ---------------------------------------------------------------------------
// Conformance: the model above is a *specification*, so it must describe the
// real `JobQueue` and not a tidier cousin of it. This drives both with the same
// deterministic pseudo-random operation sequence and compares, after every step,
// both the verdict and the whole resulting state (fence, holder, released, job).
//
// It is a differential check over 400 sequences of 12 steps, not a proof — the
// proof-shaped part is `explore` above. What it catches is the failure the model
// check cannot see on its own: a model that is internally consistent and talks
// about different code. The presented fences are always ones the queue actually
// issued (a stale one after a renewal, otherwise the current one), because
// `JobClaim` is deliberately not forgeable from outside the crate — a token a
// worker never received is not a case the protocol has to survive.
// ---------------------------------------------------------------------------

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*: deterministic, no dependency, good enough to pick steps.
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

fn pos_of(fence: &Fence) -> Pos {
    Pos {
        epoch: fence.epoch,
        generation: fence.generation,
    }
}

/// The real queue's observable state, in the model's terms.
fn observe_real(real: &JobQueue) -> State {
    let mut state = State::init();
    for (index, name) in RESOURCES.iter().enumerate() {
        let fence = real.fence(name).map(pos_of);
        let job = match real.state(name) {
            Some(JobState::Queued) | None => Job::Queued,
            Some(JobState::Claimed) => Job::Claimed,
            Some(JobState::Fired) => Job::Fired,
            Some(JobState::Disabled) => Job::Disabled,
        };
        state.res[index] = Res {
            fence,
            holder: real
                .fences()
                .holder(name)
                .and_then(|h| HOLDERS.iter().position(|x| *x == h)),
            released: real.fences().is_released(name),
            job,
        };
    }
    state
}

/// Tokens the queue issued, kept so a stale one can be presented later — the
/// partitioned-worker case.
type Token = (usize, usize, unfer_consensus::jobs::JobClaim);

#[test]
fn the_model_and_the_real_job_queue_agree_on_every_step() {
    let mut rng = Rng(0x9E37_79B9_7F4A_7C15);
    let mut compared = 0usize;
    let mut stale_presentations = 0usize;
    for sequence in 0..400 {
        let mut real = JobQueue::with_deployment("d21");
        for name in RESOURCES {
            real.enqueue(name);
            // Recovery-installed idle state: every queued job has a fence once it
            // is claimed, and `FenceTable::current` is empty before that.
            debug_assert!(real.fence(name).is_none());
        }
        let mut model = observe_real(&real);
        let mut tokens: Vec<Token> = Vec::new();

        for turn in 0..12 {
            let resource = rng.below(RESOURCES.len());
            let holder = rng.below(HOLDERS.len());
            let mut op = Op::ALL[rng.below(Op::ALL.len())];

            // An operation that needs a token needs one the worker received for
            // this resource and holder. With none, the step is a claim instead —
            // otherwise the model and the queue would both be asked to do
            // something neither has a token for, which proves nothing.
            let candidates: Vec<usize> = tokens
                .iter()
                .enumerate()
                .filter(|(_, (r, h, _))| *r == resource && *h == holder)
                .map(|(i, _)| i)
                .collect();
            if candidates.is_empty() && !matches!(op, Op::Claim | Op::Reclaim) {
                op = Op::Claim;
            }
            // The real generation space is `u64`; the model's top is MAX_GEN so a
            // model check can reach the epoch-advance rule. Conformance therefore
            // stays inside the non-overflow region: a renewal at the abstracted
            // top would compare the model's `(epoch + 1, 1)` against the real
            // `(epoch, generation + 1)`, which is the abstraction showing through,
            // not a disagreement. The overflow rule itself has its own unit test
            // against the real table.
            if op == Op::Renew && model.res[resource].fence.map(|p| p.generation) == Some(MAX_GEN) {
                op = Op::Release;
            }
            let chosen = if matches!(op, Op::Claim | Op::Reclaim) {
                None
            } else {
                Some(candidates[rng.below(candidates.len())])
            };
            let presented = chosen.map(|i| pos_of(tokens[i].2.fence()));
            let stale_presented =
                presented.is_some() && real.fence(RESOURCES[resource]).map(pos_of) != presented;

            let step = Step {
                op,
                resource,
                holder,
                presented,
            };
            let modeled = apply_op(&model, &step, Mutation::None, u64::MAX);

            // The same step on the real queue, presenting the token it issued.
            let real_result: Result<(), ()> = match (op, chosen) {
                (Op::Claim | Op::Reclaim, _) => {
                    match real.claim(RESOURCES[resource], HOLDERS[holder]) {
                        Ok(claim) => {
                            tokens.push((resource, holder, claim));
                            Ok(())
                        }
                        Err(_) => Err(()),
                    }
                }
                (_, Some(index)) => {
                    let token = tokens[index].2.clone();
                    match op {
                        Op::Renew => real.renew(&token).map(|claim| {
                            tokens.push((resource, holder, claim));
                        }),
                        Op::Release => real.unclaim(&token),
                        Op::Settle => {
                            let mut sink = unfer_consensus::jobs::OrderedMockSink::new();
                            real.settle(&token, &mut sink, "payload")
                        }
                        Op::Disable => real.disable(&token),
                        Op::Claim | Op::Reclaim => unreachable!("handled above"),
                    }
                    .map_err(|_| ())
                }
                (_, None) => Err(()),
            };
            let accepted_model = modeled.is_ok();
            let accepted_real = real_result.is_ok();
            assert_eq!(
                accepted_model,
                accepted_real,
                "sequence {sequence} turn {turn}: model says {} for {}; the real queue says {}",
                if accepted_model { "accept" } else { "refuse" },
                step.label(),
                if accepted_real { "accept" } else { "refuse" }
            );
            if stale_presented {
                // A token the queue did not issue as current: it must be refused,
                // and the model must have refused it for the same reason.
                stale_presentations += 1;
                assert!(
                    !accepted_real && !accepted_model,
                    "sequence {sequence} turn {turn}: a stale token was accepted by {} ({})",
                    if accepted_real {
                        "the queue"
                    } else {
                        "the model"
                    },
                    step.label()
                );
            }
            if let Ok(next) = modeled {
                model = next;
            }
            // Whole-state equality, not just the verdict: the fence, holder,
            // released flag and job state must match after every accepted step.
            assert_eq!(
                model,
                observe_real(&real),
                "sequence {sequence} turn {turn}: state diverged after {}",
                step.label()
            );
            if let Some(v) = violations(&model).first() {
                panic!("model invariant violated in conformance run: {v}");
            }
            compared += 1;
        }
    }
    println!(
        "conformance: {compared} steps compared, 0 disagreements, {stale_presentations} stale tokens presented, 0 accepted"
    );
}

/// A guard that the conformance driver actually exercised the interesting paths:
/// without this, a driver that always claims and releases could compare 4800
/// uninteresting steps and report agreement.
#[test]
fn conformance_covers_stale_tokens_and_every_operation() {
    let mut rng = Rng(0xA5A5_5A5A_1234_5678);
    let mut operations = BTreeSet::new();
    let stale_accepts = 0usize;
    let mut stale_presentations = 0usize;
    for _sequence in 0..400 {
        let mut real = JobQueue::with_deployment("d21");
        for name in RESOURCES {
            real.enqueue(name);
        }
        let mut tokens: Vec<Token> = Vec::new();
        for _turn in 0..12 {
            let resource = rng.below(RESOURCES.len());
            let holder = rng.below(HOLDERS.len());
            let mut op = Op::ALL[rng.below(Op::ALL.len())];
            let candidates: Vec<usize> = tokens
                .iter()
                .enumerate()
                .filter(|(_, (r, h, _))| *r == resource && *h == holder)
                .map(|(i, _)| i)
                .collect();
            if candidates.is_empty() && !matches!(op, Op::Claim | Op::Reclaim) {
                op = Op::Claim;
            }
            // The real generation space is `u64`; the model's top is MAX_GEN so a
            // model check can reach the epoch-advance rule. Conformance therefore
            // stays inside the non-overflow region: a renewal at the abstracted
            // top would compare the model's `(epoch + 1, 1)` against the real
            // `(epoch, generation + 1)`, which is the abstraction showing through,
            // not a disagreement. The overflow rule itself has its own unit test
            // against the real table.
            if op == Op::Renew
                && real.fence(RESOURCES[resource]).map(|f| f.generation) == Some(MAX_GEN)
            {
                op = Op::Release;
            }
            let chosen = if matches!(op, Op::Claim | Op::Reclaim) {
                None
            } else {
                Some(candidates[rng.below(candidates.len())])
            };
            if chosen.is_some() && matches!(op, Op::Renew | Op::Release | Op::Settle | Op::Disable)
            {
                operations.insert(op);
            }
            if matches!(op, Op::Claim | Op::Reclaim) {
                operations.insert(op);
            }
            match (op, chosen) {
                (Op::Claim | Op::Reclaim, _) => {
                    if let Ok(claim) = real.claim(RESOURCES[resource], HOLDERS[holder]) {
                        tokens.push((resource, holder, claim));
                        operations.insert(Op::Claim);
                    }
                }
                (_, Some(index)) => {
                    let token = tokens[index].2.clone();
                    let stale =
                        real.fence(RESOURCES[resource]).map(pos_of) != Some(pos_of(token.fence()));
                    let result = match op {
                        Op::Renew => real.renew(&token).map(|c| {
                            tokens.push((resource, holder, c));
                        }),
                        Op::Release => real.unclaim(&token),
                        Op::Settle => {
                            let mut sink = unfer_consensus::jobs::OrderedMockSink::new();
                            real.settle(&token, &mut sink, "payload")
                        }
                        Op::Disable => real.disable(&token),
                        Op::Claim | Op::Reclaim => unreachable!(),
                    };
                    if stale {
                        assert!(
                            result.is_err(),
                            "the queue accepted a token that is not current for {}",
                            RESOURCES[resource]
                        );
                        stale_presentations += 1;
                    }
                    let _ = &stale_accepts;
                }
                (_, None) => {}
            }
        }
    }
    for op in Op::ALL {
        assert!(
            operations.contains(&op),
            "conformance never exercised {}",
            op.label()
        );
    }
    assert!(
        stale_presentations > 0,
        "no stale token was ever presented; the stale paths were not exercised"
    );
    assert_eq!(
        stale_accepts, 0,
        "a stale token was accepted somewhere in the coverage run"
    );
    println!(
        "conformance coverage: {} operations, {stale_presentations} stale tokens presented, 0 accepted",
        operations.len()
    );
}

fn flat(t: &Tensor) -> Vec<f32> {
    t.flatten_all()
        .expect("flatten")
        .to_vec1::<f32>()
        .expect("to vec")
}

/// The posterior target: either the plain Brier MLP objective, or NLL on the
/// fit rows plus Brier on a held-out, noisily labelled calibration split.
#[derive(Clone)]
enum PosteriorHead {
    Plain(MlpHeadPotential),
    Calibrated(CalibratedMlpPotential),
}

impl PosteriorHead {
    fn flat_size(&self) -> usize {
        match self {
            Self::Plain(p) => p.flat_size(),
            Self::Calibrated(p) => p.flat_size(),
        }
    }
}

impl Potential for PosteriorHead {
    fn n_terms(&self) -> usize {
        match self {
            Self::Plain(p) => p.n_terms(),
            Self::Calibrated(p) => p.n_terms(),
        }
    }

    fn mean_loss(&self, theta: &Tensor) -> f64 {
        match self {
            Self::Plain(p) => p.mean_loss(theta),
            Self::Calibrated(p) => p.mean_loss(theta),
        }
    }

    fn mean_grad_with(&self, theta: &Tensor, norm: pcnl::normalize::NormGrad) -> Option<Tensor> {
        match self {
            Self::Plain(p) => p.mean_grad_with(theta, norm),
            Self::Calibrated(p) => p.mean_grad_with(theta, norm),
        }
    }

    fn label(&self) -> &'static str {
        match self {
            Self::Plain(p) => p.label(),
            Self::Calibrated(p) => p.label(),
        }
    }
}

/// Prediction always uses the fit head and the clean test split.
fn predict_head(
    table: &EmbeddingTable,
    head: &MlpHeadPotential,
    theta: &[f32],
    split: Split,
) -> Vec<f32> {
    predict_proba_mlp(table, theta, head.hidden(), split).expect("MLP prediction")
}

fn metrics_head(
    table: &EmbeddingTable,
    head: &MlpHeadPotential,
    theta: &[f32],
    split: Split,
) -> (f64, f64, f64) {
    metrics_mlp(table, theta, head.hidden(), split).expect("MLP metrics")
}

/// Full-batch Adam on the head only, returning the path for the informed basis.
fn train_head(
    pot: &MlpHeadPotential,
    steps: usize,
    lr: f64,
    every: usize,
    seed: u64,
) -> (Vec<f32>, Vec<Vec<f32>>, Vec<f64>) {
    let mut rng = rand::rngs::StdRng::seed_from_u64(seed);
    let init: Vec<f32> = (0..pot.flat_size())
        .map(|_| rng.random_range(-0.01f32..0.01))
        .collect();
    let mut theta = Tensor::from_vec(init, pot.flat_size(), &Device::Cpu).expect("theta");
    let mut m = Tensor::zeros(pot.flat_size(), DType::F32, &Device::Cpu).expect("m");
    let mut v = Tensor::zeros(pot.flat_size(), DType::F32, &Device::Cpu).expect("v");
    let (b1, b2, eps) = (0.9f64, 0.999f64, 1e-8f64);
    let mut path = vec![flat(&theta)];
    let mut trace = Vec::with_capacity(steps);
    for t in 1..=steps {
        let loss = pot.mean_loss(&theta);
        trace.push(loss);
        if !loss.is_finite() {
            break;
        }
        let Some(g) = pot.mean_grad(&theta) else {
            break;
        };
        m = m
            .affine(b1, 0.0)
            .unwrap()
            .add(&g.affine(1.0 - b1, 0.0).unwrap())
            .unwrap();
        v = v
            .affine(b2, 0.0)
            .unwrap()
            .add(&g.sqr().unwrap().affine(1.0 - b2, 0.0).unwrap())
            .unwrap();
        let mh = m.affine(1.0 / (1.0 - b1.powi(t as i32)), 0.0).unwrap();
        let vh = v.affine(1.0 / (1.0 - b2.powi(t as i32)), 0.0).unwrap();
        let denom = vh.sqrt().unwrap().affine(1.0, eps).unwrap();
        theta = (theta - mh.div(&denom).unwrap().affine(lr, 0.0).unwrap()).unwrap();
        if t % every == 0 || t == steps {
            path.push(flat(&theta));
        }
    }
    (flat(&theta), path, trace)
}

struct Bma {
    acc: f64,
    nll: f64,
    brier: f64,
    mean_draw_acc: f64,
    ece: f64,
    nll_i: Vec<f64>,
    brier_i: Vec<f64>,
}

fn ece(table: &EmbeddingTable, p: &[f32], split: Split) -> f64 {
    let pd: Vec<f64> = p.iter().map(|&v| v as f64).collect();
    expected_calibration_error(&pd, table.classes(), table.y(split), 10)
}

fn per_example(table: &EmbeddingTable, p: &[f32]) -> (Vec<f64>, Vec<f64>) {
    let c = table.classes();
    let y = table.y(Split::Test);
    let mut nll = Vec::with_capacity(y.len());
    let mut brier = Vec::with_capacity(y.len());
    for (i, &t) in y.iter().enumerate() {
        let row: Vec<f64> = p[i * c..(i + 1) * c].iter().map(|&v| v as f64).collect();
        nll.push(-row[t as usize].max(1e-12).ln());
        brier.push(pcnl::readout::brier(&row, t as usize));
    }
    (nll, brier)
}

/// BMA over a flat list of head draws, plus each draw's own accuracy.
fn bma(table: &EmbeddingTable, head: &MlpHeadPotential, draws: &[Vec<f32>]) -> Bma {
    let c = table.classes();
    let n = table.n_test();
    let y = table.y(Split::Test);
    let mut sum = vec![0.0f64; n * c];
    let mut per_draw_acc = Vec::with_capacity(draws.len());
    for theta in draws {
        let p = predict_head(table, head, theta, Split::Test);
        let mut hits = 0usize;
        for (i, &t) in y.iter().enumerate() {
            let row = &p[i * c..(i + 1) * c];
            let best = row
                .iter()
                .enumerate()
                .max_by(|a, b| a.1.total_cmp(b.1))
                .map(|(j, _)| j)
                .unwrap_or(0);
            if best == t as usize {
                hits += 1;
            }
            for (j, &v) in row.iter().enumerate() {
                sum[i * c + j] += v as f64;
            }
        }
        per_draw_acc.push(100.0 * hits as f64 / n as f64);
    }
    let k = draws.len() as f64;
    let mut acc = 0usize;
    let mut nll = 0.0f64;
    let mut brier = 0.0f64;
    for (i, &t) in y.iter().enumerate() {
        let row: Vec<f64> = (0..c).map(|j| sum[i * c + j] / k).collect();
        let best = row
            .iter()
            .enumerate()
            .max_by(|a, b| a.1.total_cmp(b.1))
            .map(|(j, _)| j)
            .unwrap_or(0);
        if best == t as usize {
            acc += 1;
        }
        nll -= row[t as usize].max(1e-12).ln();
        brier += pcnl::readout::brier(&row, t as usize);
    }
    let mean_draw_acc = per_draw_acc.iter().sum::<f64>() / k.max(1.0);
    let avg: Vec<f32> = sum.iter().map(|v| (v / k) as f32).collect();
    let (nll_i, brier_i) = per_example(table, &avg);
    let ece =
        expected_calibration_error(&avg.iter().map(|&v| v as f64).collect::<Vec<_>>(), c, y, 10);
    Bma {
        acc: 100.0 * acc as f64 / n as f64,
        nll: nll / n as f64,
        brier: brier / n as f64,
        mean_draw_acc,
        ece,
        nll_i,
        brier_i,
    }
}

struct Cell {
    basis: &'static str,
    rank: usize,
    accept_z: f64,
    accept_w: f64,
    beta: f64,
    ess: f64,
    rhat: f64,
    bma: Bma,
    eval: u64,
    secs: f64,
}

fn make_subspace(
    map: &[f32],
    path: &[Vec<f32>],
    rank: usize,
    kind: &'static str,
    cfg: &Cfg,
    p: usize,
) -> AffineSubspace {
    let basis = match kind {
        "informed" => pca_basis(path, rank, cfg.subset_seed).expect("informed basis"),
        _ => Basis::random(p, rank, cfg.subset_seed).expect("random basis"),
    };
    AffineSubspace::isotropic(map.to_vec(), basis, cfg.sigma).expect("subspace")
}

#[allow(clippy::too_many_arguments)]
fn run_restricted(
    table: &EmbeddingTable,
    map: &[f32],
    path: &[Vec<f32>],
    rank: usize,
    kind: &'static str,
    cfg: &Cfg,
    target_head: &PosteriorHead,
    head: &MlpHeadPotential,
) -> Cell {
    let subspace = make_subspace(map, path, rank, kind, cfg, head.flat_size());
    let target = SubspaceTarget::with_potential(subspace.clone(), cfg.lambda, target_head.clone());
    let started = Instant::now();
    let mut chains_z: Vec<Vec<Vec<f32>>> = Vec::with_capacity(cfg.chains);
    let mut phis: Vec<Vec<f64>> = Vec::with_capacity(cfg.chains);
    let mut accepts = 0usize;
    let mut attempts = 0usize;
    let mut final_beta = cfg.beta;
    for chain in 0..cfg.chains {
        let mut rng = rand::rngs::StdRng::seed_from_u64(
            cfg.sampler_seed ^ ((chain as u64 + 1) << 32) ^ rank as u64,
        );
        let mut z = vec![0.0f32; rank];
        let mut phi = target.phi(&z);
        let mut beta = cfg.beta;
        let mut kept = Vec::new();
        let mut trace = Vec::new();
        for t in 0..cfg.steps {
            let step = mh_pcn_z(&target, &mut z, phi, beta, &mut rng);
            phi = step.phi;
            if t < cfg.burn {
                beta = adapt_beta(beta, step.accepted, t, 0.3);
            } else {
                attempts += 1;
                accepts += usize::from(step.accepted);
                if (t - cfg.burn).is_multiple_of(cfg.thin) {
                    kept.push(z.clone());
                    trace.push(phi);
                }
            }
        }
        final_beta = beta;
        chains_z.push(kept);
        phis.push(trace);
    }
    let draws: Vec<Vec<f32>> = chains_z
        .iter()
        .flatten()
        .map(|z| subspace.lift(z))
        .collect();
    Cell {
        basis: kind,
        rank,
        accept_z: accepts as f64 / attempts.max(1) as f64,
        accept_w: f64::NAN,
        beta: final_beta,
        ess: ess_bulk(&phis),
        rhat: gelman_rubin(&phis),
        bma: bma(table, head, &draws),
        eval: target.evaluations(),
        secs: started.elapsed().as_secs_f64(),
    }
}

#[allow(clippy::too_many_arguments)]
fn run_full(
    table: &EmbeddingTable,
    map: &[f32],
    path: &[Vec<f32>],
    rank: usize,
    kind: &'static str,
    cfg: &Cfg,
    target_head: &PosteriorHead,
    head: &MlpHeadPotential,
) -> Cell {
    let p = head.flat_size();
    let subspace = make_subspace(map, path, rank, kind, cfg, p);
    let target = PotentialFullTarget::new(subspace.clone(), cfg.lambda, target_head.clone());
    let started = Instant::now();
    let mut chains_theta: Vec<Vec<Vec<f32>>> = Vec::with_capacity(cfg.chains);
    let mut phis: Vec<Vec<f64>> = Vec::with_capacity(cfg.chains);
    let (mut az, mut nz, mut aw, mut nw) = (0usize, 0usize, 0usize, 0usize);
    let mut final_beta = (cfg.beta, cfg.beta);
    for chain in 0..cfg.chains {
        let mut rng = rand::rngs::StdRng::seed_from_u64(
            cfg.sampler_seed ^ ((chain as u64 + 1) << 32) ^ rank as u64 ^ 0xf00d,
        );
        let mut z = vec![0.0f32; rank];
        let mut w = vec![0.0f32; p];
        let mut phi = target.phi(&z, &w);
        let mut bz = cfg.beta;
        let mut bw = cfg.beta;
        let mut kept = Vec::new();
        let mut trace = Vec::new();
        for t in 0..cfg.steps {
            let betas = vec![bz; rank];
            let sz = mh_pcn_z_full(&target, &mut z, &w, phi, &betas, &mut rng);
            phi = sz.phi;
            let sw = mh_pcn_w_full(&target, &z, &mut w, phi, bw, &mut rng);
            phi = sw.phi;
            if t < cfg.burn {
                bz = adapt_beta(bz, sz.accepted, t, 0.3);
                bw = adapt_beta(bw, sw.accepted, t, 0.3);
            } else {
                nz += 1;
                az += usize::from(sz.accepted);
                nw += 1;
                aw += usize::from(sw.accepted);
                if (t - cfg.burn).is_multiple_of(cfg.thin) {
                    kept.push(target.lift(&z, &w));
                    trace.push(phi);
                }
            }
        }
        final_beta = (bz, bw);
        chains_theta.push(kept);
        phis.push(trace);
    }
    let draws: Vec<Vec<f32>> = chains_theta.into_iter().flatten().collect();
    Cell {
        basis: kind,
        rank,
        accept_z: az as f64 / nz.max(1) as f64,
        accept_w: aw as f64 / nw.max(1) as f64,
        beta: final_beta.0,
        ess: ess_bulk(&phis),
        rhat: gelman_rubin(&phis),
        bma: bma(table, head, &draws),
        eval: target.evaluations(),
        secs: started.elapsed().as_secs_f64(),
    }
}


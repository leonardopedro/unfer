//! Posterior over a multi-layer head on frozen UltraBERT embeddings.
//!
//! The encoder is `dmis-lab/UltraBERT-Embed-150M` at revision
//! `b06b367…`, used only to produce the committed `[N, 768]` CLS table.
//! Nothing in this example differentiates through it.  The object being
//! sampled is the two-hidden-layer MLP `768 → 32 → 16 → 4` (25 204 free
//! weights/biases; no head layer is frozen):
//!
//! ```text
//! p(y | e) = softmax(MLP(e; θ))
//! Φ(z,w) = λ · N · mean L(θ_map + σ(Bz + w)) + ½‖z‖² + ½‖w‖²
//! ```
//!
//! `L` is NLL by default for the Adam anchor, and the posterior default is the
//! RLCD proper score `Σ_c (p_c − y_c)²` (`--posterior-loss brier`).  That is a
//! **generalized** Bayes target, not a literal likelihood; it favors calibrated
//! probabilities.  `--posterior-loss nll` is the identical-head control.
//!
//! `--cal-per-class K --label-noise P` holds K training rows per class out of
//! the fit set, corrupts each held-out label with probability P, and adds the
//! Brier score on those rows to the posterior target.  The fit rows keep NLL
//! and every reported metric uses the clean test labels.  The default
//! `--cal-per-class 0` leaves the target as plain Brier on all training rows.
//!
//! Here `B` is the top-`r` PCA directions of the head's short Adam path
//! (`informed`) or a seeded random orthonormal basis (`random`).  `--target
//! full` (the default) adds a projected complement `w` and therefore samples
//! **all** `P` head weights; `--target restricted` integrates only the `r`
//! informed coordinates and is the cheaper comparison.  In both cases the
//! encoder's 150M weights are fixed, so no claim here is about a fine-tuning
//! posterior over the encoder.
//!
//! ```text
//! cargo run --release -p pcnl --example ultrabert_head_pcnl
//! cargo run --release -p pcnl --example ultrabert_head_pcnl -- --train-per-class 0
//! cargo run --release -p pcnl --example ultrabert_head_pcnl -- --target restricted --ranks 4,8
//! cargo run --release -p pcnl --example ultrabert_head_pcnl -- --posterior-loss nll
//! cargo run --release -p pcnl --example ultrabert_head_pcnl -- --train-per-class 0 --cal-per-class 4 --label-noise 0.2
//! cargo run --release -p pcnl --example ultrabert_head_pcnl -- --hidden 64,32
//! ```
//!
//! The default is the data-scarce probe: 8 of the 60 training rows per class
//! and the full `P`-dimensional head posterior.  `--train-per-class 0` uses all
//! 240 rows; the MLP full-data comparison is still open.
//!
//! The fixture is regenerated by `scripts/pcnl-ultrabert-embed` and its
//! provenance (model revision, pooling, split, hash) is in the adjacent JSON.

